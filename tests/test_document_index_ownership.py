"""A generated footer does not authorize replacing a team-owned index body."""
from pathlib import Path
import sys
import tempfile
import unittest
from aikya.documentation import layout
from aikya.services import checks


class DocumentIndexOwnershipTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        self.index=self.root/'aikya/docs/indice.md';self.index.parent.mkdir(parents=True)
        self.custom='# Team navigation\n\nKeep this team note.\n\nGENERATED BY AIKYA FORGE\n'
        self.index.write_text(self.custom)

    def test_custom_footer_index_cannot_be_replaced_by_a_new_projection(self):
        with self.assertRaises(ValueError):layout.update_index(self.root)
        self.assertEqual(self.index.read_text(),self.custom)

    def test_custom_footer_index_blocks_document_creation_before_the_first_effect(self):
        with self.assertRaises(ValueError):layout.write_document(self.root,'architecture/architecture-overview.md','# Architecture\n\nObserved module.\n')
        self.assertEqual(self.index.read_text(),self.custom)
        self.assertFalse((self.root/'aikya/docs/architecture').exists())

    def test_native_snapshot_refuses_a_custom_index_without_storing_a_stale_candidate(self):
        (self.root/'value.py').write_text('VALUE = 1\n');(self.root/'test.py').write_text('print("TAP version 13\\n1..1\\nok 1 - value")\n')
        args=dict(change_id='index-proof',scope=['value.py','test.py'],session_id='author',objective='Verify value',
            acceptance=['Value is one'],tdd_paths=['test.py'],definitions=[dict(name='tests',argv=[sys.executable,'-I','-B','test.py'],
            cwd='.',report_format='tap',timeout_seconds=3,max_output_bytes=65536)])
        with self.assertRaises(ValueError):checks.preview_snapshot(self.root,**args)
        self.assertEqual(self.index.read_text(),self.custom);self.assertFalse((self.root/'.aikya').exists())

    def test_known_english_and_spanish_projections_can_be_updated(self):
        for title,language in (('Document index','en'),('Índice de documentos','es')):
            self.index.write_text('# '+title+'\n\nGENERATED BY AIKYA FORGE\n')
            layout.write_document(self.root,'architecture/architecture-overview.md','# Architecture\n\nObserved module.\n')
            layout.update_index(self.root,language=language)
            self.assertIn('architecture/architecture-overview.md',self.index.read_text())
            self.assertTrue(self.index.read_text().startswith('# '+title))
            self.assertEqual(self.index.read_text().splitlines().count('GENERATED BY AIKYA FORGE'),1)


if __name__=='__main__':unittest.main()
