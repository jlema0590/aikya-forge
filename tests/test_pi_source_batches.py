"""Exact scoped source batches retain partial effects and never replay uncertain writes."""
import importlib
import importlib.util
import json
import os
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch
from aikya.services import checks


class SourceBatchTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(importlib.util.find_spec('aikya.services.source_batches'),'Native source batches are absent')
        self.batch=importlib.import_module('aikya.services.source_batches')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        (self.root/'left.py').write_text('VALUE = 1\n');(self.root/'right.py').write_text('VALUE = 2\n')
        (self.root/'test.py').write_text('print("TAP version 13\\n1..1\\nok 1 - value")\n')
        definition=dict(name='tests',argv=[sys.executable,'-I','-B','test.py'],cwd='.',report_format='tap',timeout_seconds=3,max_output_bytes=65536)
        args=dict(change_id='multi',scope=['left.py','right.py','nested/new.py','test.py'],session_id='author',
            objective='Update both values',acceptance=['Both values are updated'],tdd_paths=['test.py'],definitions=[definition])
        plan=checks.preview_snapshot(self.root,**args);checks.apply_snapshot(self.root,plan,approved=True)
        self.intent=dict(change_id='multi',operations=[dict(path='left.py',edits=[dict(old='VALUE = 1',new='VALUE = 3')]),
            dict(path='right.py',content='VALUE = 4\n')])
        self.key=os.urandom(32);self.pending=self.root/'.aikya/pi/batches/pending.json'

    def grant(self,**options):return self.batch.issue(self.root,'author',self.intent,self.key,**options)

    def apply(self,token=None):return self.batch.apply(self.root,'author',self.intent,token or self.grant(),self.key)

    def test_preview_shows_exact_edits_without_writing_any_effect(self):
        value=self.batch.preview(self.root,self.intent,session='author')
        self.assertEqual(value['files'][0]['edits'],[dict(old='VALUE = 1',new='VALUE = 3')])
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 1\n')
        self.assertFalse((self.root/'.aikya/pi/batches').exists())

    def test_real_batch_changes_both_files_and_records_no_tests(self):
        result=self.apply();self.assertEqual(result['status'],'written')
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 3\n')
        self.assertEqual((self.root/'right.py').read_text(),'VALUE = 4\n')
        self.assertEqual(result['checks'],'not_run');self.assertFalse(result['delivery_authorized'])
        body=(self.root/result['report']).read_text();self.assertTrue(body.endswith('GENERATED BY AIKYA HARNESS\n'))
        self.assertIn('/validation/multi/',result['report']);self.assertFalse(self.pending.exists())
        refreshed=checks.refresh_preview(self.root,'multi','author');self.assertIsNotNone(refreshed)

    def test_large_file_can_receive_a_small_exact_patch(self):
        # Remain below the common physical-line cap while exceeding full replacement.
        path=self.root/'left.py'
        path.write_text('VALUE = 1\n'+('# '+('x'*70)+'\n')*500)
        checks.apply_snapshot(self.root,checks.refresh_preview(self.root,'multi','author'),approved=True)
        before=path.read_text();self.intent['operations']=self.intent['operations'][:1]
        self.apply();self.assertEqual(path.read_text(),'VALUE = 3\n'+before.split('\n',1)[1])

    def test_create_parents_and_delete_are_explicit_scoped_operations(self):
        self.intent['operations']=[dict(path='nested/new.py',content='NEW = True\n'),dict(path='right.py',delete=True)]
        value=self.batch.preview(self.root,self.intent,session='author')
        deletion=next(f for f in value['files'] if f['path']=='right.py')
        self.assertEqual(deletion['content'],'VALUE = 2\n')
        self.apply();self.assertEqual((self.root/'nested/new.py').read_text(),'NEW = True\n')
        self.assertFalse((self.root/'right.py').exists())

    def test_ambiguous_missing_or_overlapping_anchors_are_refused_without_effect(self):
        for edits in ([dict(old='missing',new='x')],[dict(old='VALUE',new='x'),dict(old='VALUE = 1',new='y')],
                      [dict(old='',new='x')],[dict(old='1',new='x'),dict(old='1',new='y')]):
            intent=dict(change_id='multi',operations=[dict(path='left.py',edits=edits)])
            with self.subTest(edits=edits),self.assertRaises(ValueError):self.batch.preview(self.root,intent,session='author')
        (self.root/'left.py').write_text('VALUE = 1\nVALUE = 1\n')
        checks.apply_snapshot(self.root,checks.refresh_preview(self.root,'multi','author'),approved=True)
        with self.assertRaises(ValueError):self.batch.preview(self.root,self.intent,session='author')
        self.assertFalse(self.pending.exists())

    def test_self_overlapping_anchor_is_ambiguous_in_the_original_file(self):
        (self.root/'left.py').write_text('TEXT = "ababa"\n')
        checks.apply_snapshot(self.root,checks.refresh_preview(self.root,'multi','author'),approved=True)
        self.intent['operations']=[dict(path='left.py',edits=[dict(old='aba',new='x')])]
        with self.assertRaises(ValueError):self.grant()

    def test_case_aliases_and_file_parent_collisions_are_refused_before_effects(self):
        from aikya.services.batch_inputs import prepare
        for names in (('new.py','NEW.py'),('parent.py','parent.py/child.py')):
            with self.subTest(names=names),self.assertRaises(ValueError):
                prepare(self.root,[dict(path=name,content='NEW = True\n') for name in names])
        self.assertFalse((self.root/'new.py').exists());self.assertFalse((self.root/'parent.py').exists())

    def test_scope_session_duplicate_destinations_and_control_paths_are_refused(self):
        for operations in ([dict(path='other.py',content='x\n')],[dict(path='.aikya/owned.py',content='x')],
                           [dict(path='left.py',content='x'),dict(path='left.py',delete=True)]):
            with self.subTest(operations=operations),self.assertRaises(ValueError):
                self.batch.preview(self.root,dict(change_id='multi',operations=operations),session='author')
        with self.assertRaises(ValueError):self.batch.preview(self.root,self.intent,session='other')
        self.assertFalse(self.pending.exists())

    def test_grant_binds_content_source_session_and_time_and_is_consumed_once(self):
        token=self.grant(now=100,ttl=2)
        with self.assertRaises(ValueError):self.batch.apply(self.root,'author',self.intent,token,self.key,now=103)
        token=self.grant()
        with self.assertRaises(ValueError):self.batch.apply(self.root,'other',self.intent,token,self.key)
        changed=json.loads(json.dumps(self.intent));changed['operations'][1]['content']='VALUE = 9\n'
        with self.assertRaises(ValueError):self.batch.apply(self.root,'author',changed,token,self.key)
        self.apply(token)
        with self.assertRaises(ValueError):self.apply(token)

    def test_stale_source_is_rejected_before_the_first_effect(self):
        token=self.grant();(self.root/'right.py').write_text('OWNER = 9\n')
        with self.assertRaises(ValueError):self.apply(token)
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 1\n');self.assertFalse(self.pending.exists())

    def test_changed_report_language_revokes_an_unconsumed_batch_grant(self):
        token=self.grant()
        (self.root/'.aikya/docs-policy.json').write_text('{"schema_version":1,"language":"es"}')
        with self.assertRaises(ValueError):self.apply(token)
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 1\n');self.assertFalse(self.pending.exists())

    def test_binary_deletion_is_outside_the_text_batch_contract(self):
        (self.root/'left.py').write_bytes(b'not\x00text')
        checks.apply_snapshot(self.root,checks.refresh_preview(self.root,'multi','author'),approved=True)
        self.intent['operations']=[dict(path='left.py',delete=True)]
        with self.assertRaises(ValueError):self.grant()
        self.assertEqual((self.root/'left.py').read_bytes(),b'not\x00text')

    def test_failed_second_effect_retains_first_and_preserves_concurrent_edit(self):
        token=self.grant();original=self.batch.perform
        def concurrent(root,item):
            result=original(root,item)
            if item['path']=='left.py':(root/'right.py').write_text('OWNER = 9\n')
            return result
        with patch.object(self.batch,'perform',side_effect=concurrent):
            with self.assertRaises(ValueError):self.apply(token)
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 3\n')
        self.assertEqual((self.root/'right.py').read_text(),'OWNER = 9\n');self.assertTrue(self.pending.exists())
        with self.assertRaises(ValueError):self.apply(token)

    def test_line_policy_is_checked_on_final_patched_content(self):
        self.intent['operations']=[dict(path='left.py',edits=[dict(old='VALUE = 1\n',new='x\n'*1001)])]
        with self.assertRaises(ValueError):self.grant()
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 1\n')

    def test_changed_binding_or_foreign_candidate_cannot_reuse_a_grant(self):
        token=self.grant()
        # Another confirmed snapshot changes the candidate even at the same bytes.
        plan=checks.refresh_preview(self.root,'multi','author');checks.apply_snapshot(self.root,plan,approved=True)
        with self.assertRaises(ValueError):self.apply(token)
        self.assertFalse(self.pending.exists())

    def test_orphaned_pre_effect_reservation_blocks_a_new_batch(self):
        token=self.grant();original=self.batch.atomic_write
        def interrupted(path,*args,**kwargs):
            if str(path).endswith('/batches/pending.json'):raise OSError('Interrupted before pending pointer')
            return original(path,*args,**kwargs)
        with patch.object(self.batch,'atomic_write',side_effect=interrupted):
            with self.assertRaises(OSError):self.apply(token)
        self.assertFalse(self.pending.exists())
        with self.assertRaises(ValueError):self.grant()
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 1\n')

    def test_pending_batch_blocks_a_new_single_file_grant(self):
        token=self.grant()
        with patch.object(self.batch,'finish',side_effect=OSError('Interrupted after source effects')):
            with self.assertRaises(OSError):self.apply(token)
        from aikya.services import authorization
        with self.assertRaises(ValueError):authorization.issue(self.root,'author',dict(path='right.py',content='NEW = True\n'),self.key)

    def recovery(self):
        self.assertIsNotNone(importlib.util.find_spec('aikya.services.batch_recovery'),'Native batch recovery is absent')
        return importlib.import_module('aikya.services.batch_recovery')

    def interrupted(self):
        token=self.grant()
        with patch.object(self.batch,'finish',side_effect=OSError('Interrupted after all source writes')):
            with self.assertRaises(OSError):self.apply(token)
        return token

    def test_batch_recovery_without_a_pending_attempt_is_read_only(self):
        value=self.recovery().preview(self.root,'author')
        self.assertEqual(value['status'],'nothing_pending');self.assertFalse((self.root/'.aikya/pi/batches').exists())

    def test_complete_effects_can_be_reconciled_without_rewriting_source(self):
        token=self.interrupted();recovery=self.recovery();value=recovery.preview(self.root,'author')
        self.assertEqual(value['status'],'reconciliation_ready')
        before={p:((self.root/p).read_bytes(),(self.root/p).stat().st_mtime_ns) for p in ('left.py','right.py')}
        with self.assertRaises(ValueError):recovery.apply(self.root,value['plan'])
        with patch.object(self.batch,'perform',side_effect=AssertionError('Must not replay source effects')):
            result=recovery.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'reconciled');self.assertEqual(result['checks'],'not_run')
        self.assertFalse(self.pending.exists())
        self.assertEqual(before,{p:((self.root/p).read_bytes(),(self.root/p).stat().st_mtime_ns) for p in before})
        with self.assertRaises(ValueError):self.apply(token)
        with self.assertRaises(ValueError):recovery.apply(self.root,value['plan'],approved=True)

    def test_partial_effects_are_manual_and_preserved(self):
        original=self.batch.perform
        def interrupted(root,item):
            original(root,item);raise OSError('Interrupted after first effect')
        with patch.object(self.batch,'perform',side_effect=interrupted):
            with self.assertRaises(OSError):self.apply()
        value=self.recovery().preview(self.root,'author')
        self.assertEqual(value['status'],'manual_reconciliation');self.assertIsNone(value['plan'])
        self.assertEqual((self.root/'left.py').read_text(),'VALUE = 3\n')
        self.assertEqual((self.root/'right.py').read_text(),'VALUE = 2\n');self.assertTrue(self.pending.exists())

    def test_recovery_refuses_changed_source_after_confirmation_preview(self):
        self.interrupted();recovery=self.recovery();value=recovery.preview(self.root,'author')
        (self.root/'right.py').write_text('OWNER = 9\n')
        with self.assertRaises(ValueError):recovery.apply(self.root,value['plan'],approved=True)
        self.assertEqual((self.root/'right.py').read_text(),'OWNER = 9\n');self.assertTrue(self.pending.exists())

    def test_recovery_requires_original_author_and_matching_signed_reservation(self):
        self.interrupted();recovery=self.recovery()
        with self.assertRaises(ValueError):recovery.preview(self.root,'other-author')
        value=json.loads(self.pending.read_text());value['mac']='0'*64;self.pending.write_text(json.dumps(value))
        with self.assertRaises(ValueError):recovery.preview(self.root,'author')
        self.assertTrue(self.pending.exists())

    def test_orphan_reservation_is_reported_as_manual_not_nothing_pending(self):
        self.interrupted();self.pending.unlink()
        value=self.recovery().preview(self.root,'author')
        self.assertEqual(value['status'],'manual_reconciliation');self.assertIsNone(value['plan'])



if __name__=='__main__':unittest.main()
