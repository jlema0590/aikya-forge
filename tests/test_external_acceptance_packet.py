"""An external trial packet binds current source but cannot claim executed acceptance."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from aikya.installation import managed_wheel

ROOT=Path(__file__).resolve().parents[1]


class ExternalAcceptancePacket(unittest.TestCase):
    def setUp(self):
        file=ROOT/'scripts/ci/prepare_external_acceptance.py';self.assertTrue(file.is_file(),'External trial packet preparation is absent')
        spec=importlib.util.spec_from_file_location('external_packet',file);self.module=importlib.util.module_from_spec(spec);spec.loader.exec_module(self.module)
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.base=Path(self.tmp.name).resolve();self.source=self.base/'source';self.source.mkdir()
        files={name:b'Fixture source\n' for name in managed_wheel.FILES}
        files.update({'VERSION':b'0.2.0\n','src/aikya/example.py':b'value=1\n','packages/aikya-pi/package.json':b'{"version":"0.2.0"}\n',
            'packages/aikya-pi/package-lock.json':b'{}\n','packages/aikya-pi/src/example.ts':b'export const value=1;\n',
            'aikya/docs/validation/forge-provider-procedure.md':(ROOT/'aikya/docs/validation/forge-provider-procedure.md').read_bytes()})
        for name,raw in files.items():
            p=self.source/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(raw)

    def test_packet_is_pending_and_source_changes_invalidate_its_fingerprint(self):
        first=self.module.prepare(self.source,self.base/'first')
        self.assertEqual(first['status'],'prepared_not_executed');self.assertEqual(first['version'],'0.2.0')
        review=json.loads((self.base/'first/forge-provider-acceptance.json').read_bytes())
        self.assertEqual(review['review_status'],'pending');self.assertEqual(review['observations'],[])
        self.assertEqual(set(review['checks'].values()),{'not_run'})
        self.assertEqual((self.base/'first/forge-provider-procedure.md').read_bytes(),(self.source/'aikya/docs/validation/forge-provider-procedure.md').read_bytes())
        self.assertTrue((self.base/'first/README.md').read_bytes().endswith(b'GENERATED BY AIKYA HARNESS\n'))
        (self.source/'src/aikya/example.py').write_bytes(b'value=2\n')
        second=self.module.prepare(self.source,self.base/'second')
        self.assertNotEqual(first['runtime_fingerprint'],second['runtime_fingerprint'])
        self.assertEqual(first['runtime_fingerprint'],review['runtime_fingerprint'])

    def test_existing_output_and_source_directory_are_preserved(self):
        output=self.base/'existing';output.mkdir();(output/'custom').write_bytes(b'Keep')
        with self.assertRaises(ValueError):self.module.prepare(self.source,output)
        self.assertEqual((output/'custom').read_bytes(),b'Keep')
        with self.assertRaises(ValueError):self.module.prepare(self.source,self.source/'new-output')
        self.assertFalse((self.source/'new-output').exists())

    def test_missing_procedure_fails_before_creating_output(self):
        (self.source/'aikya/docs/validation/forge-provider-procedure.md').unlink()
        with self.assertRaises(ValueError):self.module.prepare(self.source,self.base/'packet')
        self.assertFalse((self.base/'packet').exists())


if __name__=='__main__':unittest.main()
