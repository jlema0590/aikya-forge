"""Mobile adapters keep selected platform scope and canonical ODD/SDD authority."""
import json,os,tempfile,unittest
from pathlib import Path
from unittest.mock import patch
from aikya.services import engineering_workflows as native,authorization
from aikya.workflows.sdd import engine
from pi_tool_fixture import tool_path,write_tool

class MobileWorkflowTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);base=Path(self.tmp.name).resolve();self.root=base/'project';self.root.mkdir();self.bin=base/'bin';self.bin.mkdir()
        (self.root/'.harness').mkdir();self.profile()
        (self.root/'lib').mkdir();(self.root/'lib/screen.dart').write_text('class Screen {}\n')
        self.raw=dict(title='Selected mobile screen',objective='Render selected screen',acceptance=['The selected screen renders'],facts=dict(understood=False,contained_risk=True,resumable_from_request_diff=True),tasks=[dict(id='TASK-001',description='Render screen',acceptance=['AC-01'],depends_on=[],files=['lib/screen.dart'],checks=['tests'])])
    def profile(self,**changes):
        data=dict(backend='none',frontend='none',mobile='both',mobile_framework='flutter',methodology='odd',mode='existing',repository_layout='singlerepo');data.update(changes)
        (self.root/'.harness/project-profile.json').write_text(json.dumps(dict(decisions=data)))
    def preview(self,**data):return native.preview(self.root,'aikya-mobile-feature',data,'author-session')
    def create(self):
        value=self.preview(action='create',platforms=['android'],feature_id='mobile-screen',input_data=self.raw)
        return native.apply(self.root,value['plan'],approved=True)
    def test_missing_sdk_plan_is_read_only_and_does_not_claim_build_or_simulator(self):
        with patch.dict(os.environ,{'PATH':str(self.bin)}):value=self.preview(action='plan',platforms=['android'],files=['lib/screen.dart'])
        self.assertIsNone(value['plan']);self.assertEqual(value['status'],'not_configured')
        self.assertEqual(value['review']['mobile']['platforms'],['android'])
        self.assertEqual(value['review']['mobile']['build'],'not_run');self.assertEqual(value['review']['mobile']['simulator'],'not_checked')
        self.assertFalse((self.root/'aikya').exists());self.assertFalse((self.root/'.aikya').exists())
    def test_platform_outside_profile_and_opposite_platform_paths_are_refused(self):
        self.profile(mobile='android')
        for data in (dict(action='plan',platforms=['ios'],files=['lib/screen.dart']),dict(action='plan',platforms=['android'],files=['ios/Screen.swift'])):
            with self.subTest(data=data),self.assertRaises(ValueError):self.preview(**data)
        self.assertFalse((self.root/'aikya').exists())
    def test_confirmed_odd_creation_reuses_worklist_with_explicit_platform_context(self):
        (self.root/'.aikya').mkdir();(self.root/'.aikya/docs-policy.json').write_text('{"schema_version":1,"language":"es"}')
        value=self.preview(action='create',platforms=['android'],feature_id='mobile-screen',input_data=self.raw)
        with self.assertRaises(ValueError):native.apply(self.root,value['plan'])
        result=native.apply(self.root,value['plan'],approved=True)
        doc=self.root/'aikya/docs/features/mobile-screen/spec.md';self.assertTrue(doc.exists());self.assertIn('android',doc.read_text())
        self.assertEqual(doc.read_text().splitlines().count('GENERATED BY AIKYA HARNESS'),1)
        self.assertEqual(result['mobile']['acceptance'],'not_verified');self.assertEqual(result['mobile']['build'],'not_run')
        self.assertFalse((self.root/'.claude').exists())
    def test_odd_binding_reuses_current_task_scope_without_authorizing_other_files(self):
        self.create();value=self.preview(action='bind',platforms=['android'],feature_id='mobile-screen',task_id='TASK-001')
        result=native.apply(self.root,value['plan'],approved=True);self.assertEqual(result['status'],'task_bound')
        self.assertIsNotNone(authorization.preview(self.root,dict(path='lib/screen.dart',content='class Updated {}\n'),session='author-session')['workflow_revision'])
        with self.assertRaises(ValueError):authorization.preview(self.root,dict(path='other.dart',content='class Other {}\n'),session='author-session')
    def test_sdd_binding_requires_all_stage_approvals_and_explicit_scope(self):
        self.profile(methodology='sdd')
        args=dict(action='bind',platforms=['android'],spec_id='SPEC-001',task_id='TASK-001',files=['lib/screen.dart'])
        with self.assertRaises(ValueError):self.preview(**args)
        fixture=Path(__file__).resolve().parents[1]/'examples/sdd/development/order-api';data={name:json.loads((fixture/(name+'.json')).read_text()) for name in ('spec','clarify','plan','tasks')}
        engine.initialize(self.root,data['spec']);engine.clarify(self.root,'SPEC-001',data['clarify']);engine.approve(self.root,'SPEC-001','spec','owner')
        engine.create_plan(self.root,'SPEC-001',data['plan']);engine.approve(self.root,'SPEC-001','plan','owner');engine.create_tasks(self.root,'SPEC-001',data['tasks']);engine.approve(self.root,'SPEC-001','tasks','owner')
        value=self.preview(**args);result=native.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'task_bound');self.assertEqual(result['files'],['lib/screen.dart'])
        self.assertIn('mobile_scope',result,'SDD binding lost its reviewed mobile context')
        self.assertEqual(result['mobile_scope']['platforms'],['android'])
        intent=dict(path='lib/screen.dart',content='class Updated {}\n');key=b'x'*32
        grant=authorization.issue(self.root,'author-session',intent,key)
        changed=self.preview(**{**args,'platforms':['ios']});native.apply(self.root,changed['plan'],approved=True)
        with self.assertRaises(ValueError):authorization.apply_write(self.root,'author-session',intent,grant,key)
        with self.assertRaises(ValueError):authorization.preview(self.root,dict(path='other.dart',content='class Other {}\n'),session='author-session')
    def test_profile_drift_cannot_create_a_mobile_worklist(self):
        value=self.preview(action='create',platforms=['android'],feature_id='mobile-screen',input_data=self.raw)
        self.profile(mobile='ios')
        with self.assertRaises(ValueError):native.apply(self.root,value['plan'],approved=True)
        self.assertFalse((self.root/'aikya/docs/features/mobile-screen').exists())
    def test_sdk_presence_never_executes_wrappers_or_claims_compatibility(self):
        marker=self.bin/'SDK_EXECUTED';write_tool(tool_path(self.bin,'flutter'),'from pathlib import Path\nPath('+repr(str(marker))+').write_text("bad")\n')
        with patch.dict(os.environ,{'PATH':str(self.bin)}):value=self.preview(action='plan',platforms=['android'],files=['lib/screen.dart'])
        self.assertFalse(marker.exists());self.assertEqual(value['review']['mobile']['compatibility'],'not_verified')
        self.assertTrue(any(row['tool']=='flutter' and row['presence']=='found' for row in value['review']['mobile']['toolchains']))
    def test_recorded_platform_scope_cannot_be_switched_when_binding_shared_source(self):
        self.create();state=json.loads((self.root/'aikya/docs/features/mobile-screen/state.json').read_text())
        self.assertIn('mobile_scope',state,'Canonical feature lost its selected platform scope')
        self.assertEqual(state['mobile_scope']['platforms'],['android'])
        with self.assertRaises(ValueError):self.preview(action='bind',platforms=['ios'],feature_id='mobile-screen',task_id='TASK-001')
        with self.assertRaises(ValueError):self.preview(action='status',platforms=['ios'],feature_id='mobile-screen')
        self.assertFalse((self.root/'.aikya/pi/odd-workflow.json').exists())
    def test_embedded_footer_cannot_create_a_noncanonical_worklist(self):
        raw={**self.raw,'sections':{'context-and-scope':'Observed source.\n\nGENERATED BY AIKYA HARNESS\n\nOther text.'}}
        with self.assertRaises(ValueError):self.preview(action='create',platforms=['android'],feature_id='mobile-screen',input_data=raw)
        self.assertFalse((self.root/'aikya/docs/features/mobile-screen').exists())
