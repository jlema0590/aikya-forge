"""Host-neutral onboarding preserves ODD/SDD and never registers Claude assets."""
import importlib
import json
from pathlib import Path
import tempfile
import unittest
try: portable=importlib.import_module('aikya.installation.portable')
except ModuleNotFoundError:portable=None


class PortableOnboardingTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(portable,'Pi onboarding is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name).resolve()

    def answers(self,kind='development',method='odd',mode='new'):
        result=dict(project_type=kind,mode=mode,methodology=method,repository_layout='singlerepo')
        if kind=='development':result['backend']='python'
        elif kind=='infrastructure':result['infrastructure']={'iac':'terraform'}
        else:result['deployment']='docker'
        return result

    def test_new_and_existing_all_project_types_modes_and_languages(self):
        for kind in ('development','infrastructure','devops'):
            for method in ('odd','sdd'):
                for mode in ('new','existing'):
                    with self.subTest(kind=kind,method=method,mode=mode),tempfile.TemporaryDirectory() as folder:
                        root=Path(folder).resolve()
                        if mode=='existing':(root/'existing.py').write_text('class Existing: pass\n')
                        args=self.answers(kind,method,mode);language='es' if method=='sdd' else 'en'
                        plan=portable.preview(root,args,language=language)
                        self.assertFalse((root/'.harness').exists())
                        result=portable.apply(root,plan,approved=True)
                        self.assertEqual(result['status'],'initialized')
                        profile=json.loads((root/'.harness/project-profile.json').read_text())['decisions']
                        self.assertEqual(profile['methodology'],method)
                        self.assertFalse((root/'.claude').exists());self.assertFalse((root/'CLAUDE.md').exists())
                        self.assertFalse((root/'aikya/scripts').exists())
                        for document in (root/'aikya/docs').rglob('*.md'):
                            self.assertTrue(document.read_text().endswith('GENERATED BY AIKYA HARNESS\n'))
                        if mode=='existing':self.assertEqual((root/'existing.py').read_text(),'class Existing: pass\n')

    def test_interrupted_onboarding_needs_a_fresh_preview_and_can_complete(self):
        from unittest.mock import patch
        args=self.answers();plan=portable.preview(self.root,args)
        with patch.object(portable,'write_document',side_effect=OSError('simulated document interruption')):
            with self.assertRaises(OSError):portable.apply(self.root,plan,approved=True)
        with self.assertRaises(ValueError):portable.apply(self.root,plan,approved=True)
        fresh=portable.preview(self.root,args)
        self.assertEqual(portable.apply(self.root,fresh,approved=True)['status'],'initialized')
        self.assertTrue((self.root/'aikya/docs/overview.md').is_file())

    def test_initialized_new_project_can_be_analyzed_but_cannot_hide_source_inside_aikya(self):
        args=self.answers();portable.apply(self.root,portable.preview(self.root,args),approved=True)
        (self.root/'aikya/actual_source.py').write_text('class ProjectSource: pass\n')
        with self.assertRaises(ValueError):portable.preview(self.root,args)
        existing={**args,'mode':'existing'}
        plan=portable.preview(self.root,existing)
        portable.apply(self.root,plan,approved=True)
        self.assertEqual((self.root/'aikya/actual_source.py').read_text(),'class ProjectSource: pass\n')

    def test_approval_and_methodology_are_required_before_writes(self):
        args=self.answers();plan=portable.preview(self.root,args)
        with self.assertRaises(ValueError):portable.apply(self.root,plan)
        args.pop('methodology')
        with self.assertRaises(ValueError):portable.preview(self.root,args)
        self.assertEqual(list(self.root.iterdir()),[])

    def test_existing_source_or_custom_profile_changed_since_preview_is_preserved(self):
        (self.root/'existing.py').write_text('VALUE = 1\n')
        with self.assertRaises(ValueError):portable.preview(self.root,self.answers())
        plan=portable.preview(self.root,self.answers(mode='existing'))
        (self.root/'existing.py').write_text('VALUE = 2\n')
        with self.assertRaises(ValueError):portable.apply(self.root,plan,approved=True)
        self.assertFalse((self.root/'.harness').exists())
        (self.root/'.harness').mkdir();profile=self.root/'.harness/project-profile.json';profile.write_text('{"custom":true}')
        with self.assertRaises(ValueError):portable.preview(self.root,self.answers(mode='existing'))
        self.assertEqual(profile.read_text(),'{"custom":true}')


if __name__=='__main__':unittest.main()
