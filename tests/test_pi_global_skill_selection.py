"""Project selection pins inert library bytes and never activates global discovery."""
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from aikya.services import selected_skills,skill_library


class GlobalSelectionTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.base=Path(self.tmp.name).resolve()
        self.app=self.base/'application';self.source=self.base/'example-skill';self.source.mkdir()
        self.root=self.base/'project';self.root.mkdir()
        self.env=patch.dict('os.environ',{'AIKYA_INSTALL_ROOT':str(self.app)});self.env.start();self.addCleanup(self.env.stop)
        self.original=b'---\nname: example-skill\ndescription: Explain the selected conventions\n---\nUse reviewed local facts.\n'
        (self.source/'SKILL.md').write_bytes(self.original)
        value=skill_library.preview(str(self.source));self.installed=skill_library.apply(value['plan'],approved=True)
        self.descriptor=dict(kind='global',name='example-skill',source_hash=self.installed['source_hash'])

    def test_global_selection_preview_has_no_project_effect_and_names_the_exact_version(self):
        value=selected_skills.preview(self.root,self.descriptor)
        self.assertEqual(value['plan']['source'],self.descriptor)
        self.assertEqual(value['review']['name'],'example-skill');self.assertEqual(value['review']['activation'],'explicit_only')
        self.assertEqual(list(self.root.iterdir()),[])

    def test_selected_global_version_is_copied_to_project_and_survives_upstream_removal(self):
        import shutil
        shutil.rmtree(self.source)
        value=selected_skills.preview(self.root,self.descriptor);result=selected_skills.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'installed')
        entry=selected_skills.resolve(self.root)['skills'][0]
        self.assertEqual(entry['source_hash'],self.installed['source_hash'])
        self.assertTrue(entry['file'].startswith('.aikya/pi/skills/packages/'))
        self.assertTrue((self.root/entry['file']).read_bytes().endswith(b'GENERATED BY AIKYA FORGE\n'))
        self.assertEqual(len(skill_library.status()['skills']),1)

    def test_unversioned_or_foreign_global_selection_cannot_adopt_latest(self):
        for value in (dict(kind='global',name='example-skill'),dict(kind='global',name='another',source_hash=self.installed['source_hash'])):
            with self.subTest(value=value),self.assertRaises(ValueError):selected_skills.preview(self.root,value)
        self.assertEqual(list(self.root.iterdir()),[])

    def test_global_cache_changed_during_confirmation_never_creates_project_selection(self):
        value=selected_skills.preview(self.root,self.descriptor)
        changed=Path(self.installed['package'])/'files/SKILL.md';changed.write_text('User changed global cached instructions')
        with self.assertRaises(ValueError):selected_skills.apply(self.root,value['plan'],approved=True)
        self.assertEqual(list(self.root.iterdir()),[]);self.assertEqual(changed.read_text(),'User changed global cached instructions')

    def test_global_local_collision_never_silently_overwrites_a_project_choice(self):
        local=selected_skills.preview(self.root,str(self.source));selected_skills.apply(self.root,local['plan'],approved=True)
        before=selected_skills.resolve(self.root)
        with self.assertRaises(ValueError):selected_skills.preview(self.root,self.descriptor)
        self.assertEqual(selected_skills.resolve(self.root),before)


if __name__=='__main__':unittest.main()
