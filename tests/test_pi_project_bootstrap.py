"""Native bootstrap plans and local infra generation retain real source ownership."""
import importlib,json,tempfile,unittest
from pathlib import Path
try:bootstrap=importlib.import_module('aikya.services.project_bootstrap')
except ModuleNotFoundError:bootstrap=None


class BootstrapTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(bootstrap,'Native project bootstrap service is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        (self.root/'.harness').mkdir();self.profile(dict(backend='python',methodology='odd',mode='existing',repository_layout='singlerepo'))
        (self.root/'source.py').write_text('VALUE = 1\n')
        self.project=dict(action='plan',slug='api-module',objective='Introduce the selected API boundary.',modules=[dict(name='api',path='src/api',purpose='Expose the reviewed API')],files=['src/api/value.py'],acceptance=['The API returns the expected value.'],checks=['tests'])

    def profile(self,data):
        (self.root/'.harness/project-profile.json').write_text(json.dumps(dict(decisions=data)))

    def preview(self,command,data):return bootstrap.preview(self.root,command,data,'author-session')

    def test_project_plan_has_no_effects_and_does_not_claim_implementation(self):
        value=self.preview('aikya-project',self.project)
        self.assertEqual(value['status'],'planned');self.assertIsNone(value['plan'])
        self.assertEqual(value['review']['modules'][0]['path'],'src/api')
        self.assertEqual(value['review']['checks'],['tests']);self.assertEqual(value['review']['execution'],'not_run')
        self.assertFalse((self.root/'aikya').exists());self.assertFalse((self.root/'src').exists())

    def test_project_record_is_confirmed_localized_and_never_creates_application(self):
        (self.root/'.aikya').mkdir();(self.root/'.aikya/docs-policy.json').write_text('{"schema_version":1,"language":"es"}')
        value=self.preview('aikya-project',{**self.project,'action':'record'})
        with self.assertRaises(ValueError):bootstrap.apply(self.root,value['plan'])
        result=bootstrap.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'generated');self.assertFalse((self.root/'src').exists())
        path=self.root/'aikya/docs/plan/project-api-module.md';body=path.read_text()
        self.assertIn('Objetivo',body);self.assertIn('src/api/value.py',body)
        self.assertEqual(body.splitlines().count('GENERATED BY AIKYA FORGE'),1)
        self.assertFalse((self.root/'.claude').exists())

    def test_empty_goal_private_modules_and_unknown_input_are_refused(self):
        for data in ({**self.project,'objective':''},{**self.project,'modules':[dict(name='hidden',path='.aikya',purpose='Private')]},{**self.project,'files':['../escape.py']},{**self.project,'shell':'rm -rf anything'}):
            with self.subTest(data=data),self.assertRaises(ValueError):self.preview('aikya-project',data)
        self.assertFalse((self.root/'aikya').exists())

    def test_infra_plan_is_read_only_and_generation_preserves_existing_artifacts(self):
        self.profile(dict(project_type='infrastructure',methodology='odd',mode='existing',repository_layout='singlerepo',infrastructure=dict(iac='terraform')))
        value=self.preview('aikya-infra',dict(action='plan'))
        self.assertIn('infra/terraform/versions.tf',[v['path'] for v in value['review']['artifacts']])
        self.assertFalse((self.root/'infra').exists())
        data=dict(action='generate',paths=['infra/terraform/versions.tf'])
        value=self.preview('aikya-infra',data);bootstrap.apply(self.root,value['plan'],approved=True)
        path=self.root/'infra/terraform/versions.tf';self.assertIn('required_version',path.read_text())
        path.write_text('OWNER INFRA\n');value=self.preview('aikya-infra',data)
        self.assertEqual(value['status'],'nothing_to_generate');self.assertEqual(path.read_text(),'OWNER INFRA\n')
        self.assertFalse((self.root/'infra/terraform/README.md').exists())

    def test_infra_guidance_stays_in_aikya_docs_and_remote_operations_are_not_actions(self):
        self.profile(dict(project_type='infrastructure',methodology='odd',mode='existing',repository_layout='singlerepo',infrastructure=dict(iac='terraform')))
        data=dict(action='generate',paths=['infra/terraform/versions.tf','aikya/docs/infrastructure/bootstrap.md'])
        value=self.preview('aikya-infra',data);bootstrap.apply(self.root,value['plan'],approved=True)
        body=(self.root/'aikya/docs/infrastructure/bootstrap.md').read_text()
        self.assertIn('not executed',body);self.assertTrue(body.endswith('GENERATED BY AIKYA FORGE\n'))
        for action in ('apply','destroy','deploy'):
            with self.assertRaises(ValueError):self.preview('aikya-infra',dict(action=action))

    def test_stale_source_and_sdd_scope_are_refused_before_generation(self):
        self.profile(dict(project_type='infrastructure',methodology='odd',mode='existing',repository_layout='singlerepo',infrastructure=dict(iac='terraform')))
        value=self.preview('aikya-infra',dict(action='generate',paths=['infra/terraform/versions.tf']))
        (self.root/'source.py').write_text('VALUE = 2\n')
        with self.assertRaises(ValueError):bootstrap.apply(self.root,value['plan'],approved=True)
        p=self.root/'.harness/project-profile.json';p.write_text(p.read_text().replace('odd','sdd'))
        with self.assertRaises(ValueError):self.preview('aikya-infra',dict(action='generate',paths=['infra/terraform/versions.tf']))
        self.assertFalse((self.root/'infra').exists())

    def test_existing_project_scaffold_is_planned_but_cannot_execute(self):
        value=self.preview('aikya-scaffold',dict(action='plan'))
        self.assertEqual(value['status'],'existing_project');self.assertIsNone(value['plan'])
        with self.assertRaises(ValueError):self.preview('aikya-scaffold',dict(action='prepare',generator='anything'))
        self.assertEqual((self.root/'source.py').read_text(),'VALUE = 1\n')

    def test_scaffold_plan_marks_dynamic_versions_unresolved_and_manual_stacks_honestly(self):
        self.profile(dict(backend='next',frontend='react',methodology='odd',mode='new',repository_layout='singlerepo'))
        value=self.preview('aikya-scaffold',dict(action='plan'))
        self.assertEqual(value['review']['generators'][0]['status'],'version_required')
        self.assertFalse((self.root/'.aikya').exists())
        self.profile(dict(backend='python',methodology='odd',mode='new',repository_layout='singlerepo'))
        value=self.preview('aikya-scaffold',dict(action='plan'))
        self.assertEqual(value['status'],'manual_required');self.assertEqual(value['review']['generators'],[])

    def test_linked_manifest_is_never_read_by_infra_planner(self):
        self.profile(dict(project_type='devops',methodology='odd',mode='existing',repository_layout='singlerepo',deployment='docker',infrastructure=dict(source_kind='source')))
        (self.root/'package.json').symlink_to(self.root/'source.py')
        with self.assertRaises(ValueError):self.preview('aikya-infra',dict(action='plan'))
