"""Declarative onboarding binds its selected input and preserves project ownership."""
from pathlib import Path
import tempfile,json,unittest
from aikya.services import workflows


class AnswersTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()

    def test_explicit_new_profile_previews_and_applies_without_claude_assets(self):
        profile=dict(backend='python',methodology='odd',mode='new',repository_layout='singlerepo')
        value=workflows.preview(self.root,'aikya-answers',profile,'es')
        self.assertEqual(list(self.root.iterdir()),[])
        with self.assertRaises(ValueError):workflows.apply(self.root,value)
        result=workflows.apply(self.root,value,approved=True)
        self.assertEqual(result['methodology'],'odd');self.assertFalse((self.root/'.claude').exists())
        self.assertTrue((self.root/'aikya/docs/overview.md').read_text().endswith('GENERATED BY AIKYA FORGE\n'))

    def test_answers_requires_explicit_mode_and_methodology(self):
        for profile in (dict(backend='python',methodology='odd'),dict(backend='python',mode='new'),dict(backend='python',methodology='standard',mode='new')):
            with self.subTest(profile=profile),self.assertRaises(ValueError):workflows.preview(self.root,'aikya-answers',profile)
        self.assertEqual(list(self.root.iterdir()),[])

    def test_selected_project_answers_file_is_read_only_and_bound_until_apply(self):
        self.assertTrue(hasattr(workflows,'answers_preview'),'Answers-file preview is absent')
        path=self.root/'.aikya/answers.json';path.parent.mkdir()
        profile=dict(backend='python',methodology='sdd',mode='new',repository_layout='singlerepo')
        path.write_text(json.dumps(profile));before=path.read_bytes()
        value=workflows.answers_preview(self.root,'en')
        self.assertEqual(path.read_bytes(),before);self.assertFalse((self.root/'.harness').exists())
        path.write_text(json.dumps({**profile,'methodology':'odd'}))
        with self.assertRaises(ValueError):workflows.apply(self.root,value,approved=True)
        self.assertFalse((self.root/'.harness').exists())
        value=workflows.answers_preview(self.root,'en');workflows.apply(self.root,value,approved=True)
        self.assertEqual(json.loads((self.root/'.harness/project-profile.json').read_text())['decisions']['methodology'],'odd')

    def test_existing_sources_and_established_methodology_are_preserved(self):
        (self.root/'main.py').write_text('VALUE = 1\n')
        profile=dict(backend='python',methodology='odd',mode='existing',repository_layout='singlerepo')
        value=workflows.preview(self.root,'aikya-answers',profile)
        workflows.apply(self.root,value,approved=True)
        self.assertEqual((self.root/'main.py').read_text(),'VALUE = 1\n')
        with self.assertRaises(ValueError):workflows.preview(self.root,'aikya-answers',{**profile,'methodology':'sdd'})

    def test_selected_file_cannot_follow_links_or_accept_duplicate_json_fields(self):
        self.assertTrue(hasattr(workflows,'answers_preview'),'Answers-file preview is absent')
        path=self.root/'.aikya/answers.json';path.parent.mkdir();outside=self.root/'source.json';outside.write_text('{}')
        path.symlink_to(outside)
        with self.assertRaises(ValueError):workflows.answers_preview(self.root)
        path.unlink();path.write_text('{"mode":"new","mode":"existing"}')
        with self.assertRaises(ValueError):workflows.answers_preview(self.root)

    def test_large_declarative_profile_is_refused_before_effects(self):
        profile=dict(backend='python',methodology='odd',mode='new',notes='x'*20000)
        with self.assertRaises(ValueError):workflows.preview(self.root,'aikya-answers',profile)
        self.assertEqual(list(self.root.iterdir()),[])

    def test_onboarding_overview_and_all_generated_pages_have_one_final_footer(self):
        value=workflows.preview(self.root,'aikya-answers',dict(backend='python',methodology='odd',mode='new',repository_layout='singlerepo'),'es')
        workflows.apply(self.root,value,approved=True)
        for path in (self.root/'aikya/docs').rglob('*.md'):
            text=path.read_text();self.assertEqual(text.splitlines().count('GENERATED BY AIKYA FORGE'),1,str(path))
            self.assertTrue(text.endswith('GENERATED BY AIKYA FORGE\n'))
