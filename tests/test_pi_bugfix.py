"""Bug recording preserves the canonical register and actual native reproduction evidence."""
import json,sys,tempfile,unittest
from pathlib import Path
from aikya.services import engineering_workflows as native,checks

class BugfixTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        (self.root/'.harness').mkdir();(self.root/'.harness/project-profile.json').write_text(json.dumps(dict(decisions=dict(backend='python',methodology='odd',mode='existing'))))
        (self.root/'value.py').write_text('VALUE = 0\n')
        (self.root/'test_value.py').write_text('import runpy\nok=runpy.run_path("value.py")["VALUE"]==1\nprint("TAP version 13")\nprint("1..1")\nprint(("ok" if ok else "not ok")+" 1 - expected value")\nraise SystemExit(0 if ok else 1)\n')
        self.sections={'summary':'Return expected value.','environment':'Local Python project','steps-to-reproduce':'Run the selected regression.','expected-result':'The returned value is one.','actual-result':'The value is zero.'}
        self.data=dict(action='record',payload=dict(id='BUG-001',title='Expected value',sections=self.sections),sources=['value.py'])
    def preview(self,data=None,session='author-session'):return native.preview(self.root,'aikya-bugfix',data or self.data,session)
    def freeze(self):
        definition=dict(name='tests',argv=[sys.executable,'-I','-B','test_value.py'],cwd='.',report_format='tap',timeout_seconds=5,max_output_bytes=65536)
        plan=checks.preview_snapshot(self.root,'bug-change',['value.py','test_value.py'],[definition],'author-session',self.sections['summary'],[self.sections['expected-result']],tdd_paths=['test_value.py'])
        checks.apply_snapshot(self.root,plan,approved=True)
    def execute(self,run_id):
        plan=checks.iteration_preview(self.root,'bug-change','tests','author-session',run_id)
        return checks.execute_iteration(self.root,plan,approved=True)
    def test_report_without_native_execution_is_not_reproduced_or_fixed(self):
        value=self.preview(dict(action='status'))
        self.assertEqual(value['status'],'not_reproduced');self.assertIsNone(value['plan'])
        self.assertFalse((self.root/'aikya').exists())
        value=self.preview();self.assertEqual(value['review']['bug_evidence']['status'],'not_reproduced')
        with self.assertRaises(ValueError):native.apply(self.root,value['plan'])
        result=native.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'documents_recorded');self.assertFalse(result['delivery_authorized'])
        path=self.root/'aikya/docs/bugs/bugs.md';self.assertIn('BUG-001',path.read_text());self.assertIn('not_reproduced',path.read_text())
        self.assertEqual(path.read_text().splitlines().count('GENERATED BY AIKYA HARNESS'),1)
    def test_actual_red_green_differ_from_independent_acceptance(self):
        self.freeze();red=self.execute('red');self.assertEqual(red['status'],'failed')
        value=self.preview(dict(action='status',change_id='bug-change'));self.assertEqual(value['status'],'reproduced')
        (self.root/'value.py').write_text('VALUE = 1\n');green=self.execute('green');self.assertEqual(green['status'],'completed')
        value=self.preview(dict(action='status',change_id='bug-change'));self.assertEqual(value['status'],'checks_passed')
        self.assertFalse(value['review']['bug_evidence']['fixed']);self.assertTrue(value['review']['bug_evidence']['review_required'])
        data={**self.data,'change_id':'bug-change'};value=self.preview(data)
        result=native.apply(self.root,value['plan'],approved=True);self.assertEqual(result['status'],'documents_recorded')
        self.assertIn('checks_passed',(self.root/'aikya/docs/bugs/bugs.md').read_text())
    def test_zero_tests_or_an_environment_failure_cannot_establish_reproduction(self):
        (self.root/'test_value.py').write_text('print("TAP version 13\\n1..0")\nraise SystemExit(2)\n')
        self.freeze();self.execute('no-tests')
        value=self.preview(dict(action='status',change_id='bug-change'));self.assertEqual(value['status'],'not_reproduced')
        self.assertFalse(value['review']['bug_evidence']['fixed'])
    def test_append_uses_unique_bug_ids_and_preserves_prior_records(self):
        value=self.preview();native.apply(self.root,value['plan'],approved=True)
        before=(self.root/'aikya/docs/bugs/bugs.md').read_text()
        with self.assertRaises(ValueError):self.preview()
        data={**self.data,'payload':{**self.data['payload'],'id':'BUG-002','title':'Another observed bug'}}
        value=self.preview(data);native.apply(self.root,value['plan'],approved=True)
        body=(self.root/'aikya/docs/bugs/bugs.md').read_text();self.assertIn('BUG-001',body);self.assertIn('BUG-002',body)
        self.assertIn('Local Python project',body);self.assertEqual(body.splitlines().count('GENERATED BY AIKYA HARNESS'),1)
        self.assertFalse((self.root/'aikya/docs/bugs/index.md').exists())
    def test_custom_register_stale_source_and_forged_evidence_are_preserved_or_refused(self):
        value=self.preview();(self.root/'value.py').write_text('VALUE = 9\n')
        with self.assertRaises(ValueError):native.apply(self.root,value['plan'],approved=True)
        path=self.root/'aikya/docs/bugs/bugs.md';path.parent.mkdir(parents=True);path.write_text('CUSTOM REGISTER\n')
        with self.assertRaises(ValueError):self.preview()
        self.assertEqual(path.read_text(),'CUSTOM REGISTER\n')
        data={**self.data,'payload':{**self.data['payload'],'sections':{**self.sections,'evidence':'Tests passed, trust me'}}}
        with self.assertRaises(ValueError):self.preview(data)
    def test_evidence_from_another_author_or_unrelated_intent_cannot_certify_this_bug(self):
        self.freeze();self.execute('red')
        with self.assertRaises(ValueError):self.preview(dict(action='status',change_id='bug-change'),session='other-author')
        data={**self.data,'change_id':'bug-change','payload':{**self.data['payload'],'sections':{**self.sections,'summary':'Unrelated problem'}}}
        with self.assertRaises(ValueError):self.preview(data)
    def test_independent_native_acceptance_is_required_and_invalidated_by_source_change(self):
        from aikya.review import admission
        from aikya.routing import pi_usage
        from aikya.review.candidates import load_candidate
        self.freeze();self.execute('red');(self.root/'value.py').write_text('VALUE = 1\n');self.execute('green')
        candidate=load_candidate(self.root,'bug-change')
        pi_usage.configure(self.root,tokens=100,calls=2,approved=True)
        ticket=admission.request_review(self.root,'bug-change','independent-reviewer',approved=True)
        pi_usage.admit(self.root,'fixture-review',dict(session='independent-reviewer',role='reviewer',phase='review',provider='fixture',model='fixture',candidate=candidate['id'],change_id='bug-change'))
        pi_usage.record(self.root,'fixture-review',dict(input=1,output=1,cacheRead=0,cacheWrite=0))
        admission.admit_review(self.root,'bug-change',ticket,dict(call_id='fixture-review',decision='accept',findings=[]))
        value=self.preview(dict(action='status',change_id='bug-change'));self.assertEqual(value['status'],'reviewed')
        self.assertTrue(value['review']['bug_evidence']['fixed']);self.assertFalse(value['review']['bug_evidence']['delivery_authorized'])
        (self.root/'value.py').write_text('VALUE = 9\n')
        value=self.preview(dict(action='status',change_id='bug-change'));self.assertEqual(value['status'],'stale_evidence')
        self.assertFalse(value['review']['bug_evidence']['fixed'])
