"""Local infrastructure validation records processes, never fabricated test counts."""
import importlib,json,os,stat,sys,tempfile,unittest
from pathlib import Path
from unittest.mock import patch
from pi_tool_fixture import tool_path,write_tool
try:validation=importlib.import_module('aikya.services.infra_validation')
except ModuleNotFoundError:validation=None

class InfraValidationTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(validation,'Native infrastructure validation is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);base=Path(self.tmp.name).resolve()
        self.root=base/'project';self.root.mkdir();(self.root/'.harness').mkdir()
        (self.root/'.harness/project-profile.json').write_text(json.dumps(dict(decisions=dict(project_type='infrastructure',methodology='odd',mode='existing',repository_layout='singlerepo',infrastructure=dict(iac='terraform')))))
        self.bin=base/'bin';self.bin.mkdir();self.tool=tool_path(self.bin,'terraform');self.program('print("valid syntax")\n')
        env=patch.dict(os.environ,{'PATH':str(self.bin)});env.start();self.addCleanup(env.stop)
    def program(self,body):
        write_tool(self.tool,body)
    def artifact(self):
        folder=self.root/'infra/terraform';folder.mkdir(parents=True);(folder/'versions.tf').write_text('terraform {}\n')
    def preview(self):return validation.preview(self.root,'terraform-fmt','author-session','local-check')
    def test_missing_artifacts_and_tools_are_not_configured_without_effects(self):
        result=self.preview();self.assertEqual(result['status'],'not_configured');self.assertIsNone(result['plan'])
        self.artifact();self.tool.unlink();result=self.preview()
        self.assertEqual(result['status'],'not_configured');self.assertFalse((self.root/'.aikya').exists())
    def test_confirmed_zero_exit_records_a_process_with_no_tests_or_delivery(self):
        self.artifact();value=self.preview()
        self.assertEqual(value['review']['argv'][1:],['fmt','-check','-recursive','infra/terraform'])
        with self.assertRaises(ValueError):validation.apply(self.root,value['plan'])
        result=validation.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'validated');self.assertIsNone(result['counts']);self.assertEqual(result['tests'],'not_run')
        self.assertFalse(result['delivery_authorized']);self.assertEqual(result['process']['exit_code'],0)
        self.assertTrue((self.root/result['report']).read_text().endswith('GENERATED BY AIKYA FORGE\n'))
        with self.assertRaises(ValueError):validation.apply(self.root,value['plan'],approved=True)
    def test_stale_inputs_and_changed_tool_refuse_before_execution(self):
        self.artifact();value=self.preview();self.program('raise SystemExit(6)\n')
        with self.assertRaises(ValueError):validation.apply(self.root,value['plan'],approved=True)
        self.assertFalse((self.root/'aikya/docs').exists())
    def test_failed_validator_is_not_reported_as_validated(self):
        self.artifact();self.program('raise SystemExit(6)\n');value=self.preview()
        result=validation.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'failed');self.assertEqual(result['process']['exit_code'],6)
        self.assertIsNone(result['counts'])
    def test_remote_or_arbitrary_commands_are_not_validation_recipes(self):
        for name in ('apply','destroy','terraform apply','bash'):
            with self.subTest(name=name),self.assertRaises(ValueError):validation.preview(self.root,name,'author-session','bad')
    def test_cancellation_before_execution_is_observed_without_launch(self):
        self.artifact();value=self.preview();validation.cancel(self.root,value['plan'])
        result=validation.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'cancelled');self.assertIsNone(result['process']['exit_code'])
    def test_mutating_validator_cannot_claim_success(self):
        self.artifact();self.program("from pathlib import Path\nPath('unexpected.txt').write_text('side effect')\n")
        result=validation.apply(self.root,self.preview()['plan'],approved=True)
        self.assertEqual(result['status'],'source_changed');self.assertFalse(result['delivery_authorized'])
        self.assertTrue((self.root/'unexpected.txt').exists())
    def test_uncertain_previous_execution_blocks_a_new_run(self):
        self.artifact();value=self.preview()
        with patch('aikya.services.infra_validation.capture_process',side_effect=OSError('lost host')):
            with self.assertRaises(OSError):validation.apply(self.root,value['plan'],approved=True)
        with self.assertRaises(ValueError):validation.preview(self.root,'terraform-fmt','author-session','another-check')
