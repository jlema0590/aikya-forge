"""Local and fetched skill bytes use one bounded inert metadata/package compositor."""
import unittest
from aikya.services import skill_source


class SkillByteSnapshotTests(unittest.TestCase):
    def setUp(self):
        self.assertTrue(callable(getattr(skill_source,'from_bytes',None)),'Shared byte skill compositor is absent')
        self.raw=b'---\r\nname: selected-skill\r\ndescription: Use selected facts\r\nallowed-tools: Bash\r\n---\r\nFollow the selected facts.\r\n'

    def test_captured_originals_remain_exact_while_prepared_markdown_is_canonical(self):
        data=skill_source.from_bytes({'SKILL.md':self.raw},'github:example/source@fixed',expected_name='selected-skill')
        self.assertEqual(data['raws']['SKILL.md'],self.raw);self.assertEqual(data['name'],'selected-skill')
        self.assertEqual(data['ignored_fields'],['allowed-tools'])
        self.assertTrue(data['prepared']['SKILL.md'].endswith(b'GENERATED BY AIKYA HARNESS\n'))
        self.assertNotIn(b'\r\n',data['prepared']['SKILL.md'])

    def test_unicode_resource_components_must_fit_portable_filesystem_byte_limits(self):
        with self.assertRaises(ValueError):
            skill_source.from_bytes({'SKILL.md':self.raw,'字'*100+'.md':b'Not portable'},'captured')

    def test_name_is_bound_to_the_explicit_source_selection(self):
        with self.assertRaises(ValueError):skill_source.from_bytes({'SKILL.md':self.raw},'captured',expected_name='another-skill')

    def test_traversal_aliases_devices_and_file_parent_collisions_are_refused(self):
        cases=[{'../escape':b'x'},{'skill.md':b'x'},{'CON.txt':b'x'},{'folder. /file':b'x'},
            {'a':b'x','a/b':b'x'},{'references/secret.key':b'x'},{'x:y':b'x'}]
        for extra in cases:
            with self.subTest(paths=list(extra)),self.assertRaises(ValueError):
                skill_source.from_bytes({'SKILL.md':self.raw,**extra},'captured',expected_name='selected-skill')

    def test_excessive_data_and_missing_uppercase_skill_cannot_become_partial_packages(self):
        for files in ({'skill.md':self.raw},{'SKILL.md':self.raw,**{str(i):b'x' for i in range(80)}}):
            with self.assertRaises(ValueError):skill_source.from_bytes(files,'captured',expected_name='selected-skill')

    def test_standard_wrapped_and_folded_descriptions_keep_their_complete_meaning(self):
        fronts=[b'description: Use selected facts,\n  preserve the actual interface.\n',
                b'description: >-\n  Use selected facts,\n  preserve the actual interface.\n']
        for front in fronts:
            raw=b'---\nname: selected-skill\n'+front+b'allowed-tools:\n  - Bash\n  - Read\n---\nRead current facts.\n'
            data=skill_source.from_bytes({'SKILL.md':raw},'captured',expected_name='selected-skill')
            self.assertEqual(data['description'],'Use selected facts, preserve the actual interface.')
            self.assertEqual(data['ignored_fields'],['allowed-tools'])
            self.assertEqual(data['raws']['SKILL.md'],raw)

    def test_required_metadata_aliases_and_duplicate_names_cannot_change_identity(self):
        for head in (b'name: selected-skill\ndescription: *untrusted\n',
                     b'name: selected-skill\nname: another\ndescription: Facts\n'):
            with self.assertRaises(ValueError):skill_source.from_bytes({'SKILL.md':b'---\n'+head+b'---\nRead facts.\n'},'captured',expected_name='selected-skill')


if __name__=='__main__':unittest.main()
