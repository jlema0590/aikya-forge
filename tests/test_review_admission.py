"""A reviewer needs a host ticket and an observed, candidate-bound reviewer call."""
import importlib
from pathlib import Path
import sys
import tempfile
import unittest
from aikya.review.candidates import freeze_candidate, store_candidate
from aikya.review.controller import assess_candidate
from aikya.review.executor import run_check, check_binding
from aikya.routing import pi_usage
try: admission=importlib.import_module('aikya.review.admission')
except ModuleNotFoundError: admission=None


class ReviewAdmissionTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(admission,'Independent review admission is absent')
        self.tmp=tempfile.TemporaryDirectory(); self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name).resolve(); (self.root/'source.py').write_text('VALUE = 1\n')
        script='import os;from pathlib import Path;Path(os.environ["AIKYA_TEST_REPORT"]).write_text(\'<testsuite tests="1"><testcase name="pass"/></testsuite>\')'
        definition=dict(name='tests',argv=[sys.executable,'-I','-B','-c',script],cwd='.',report_format='junit',timeout_seconds=3,max_output_bytes=65536)
        self.definition=definition
        self.candidate=freeze_candidate(self.root,'change-1',['source.py'],session_id='author',
            policy=dict(checks=['tests'],review_required=True,definitions={'tests':check_binding(self.root,definition)}))
        store_candidate(self.root,self.candidate,approved=True)
        run_check(self.root,'change-1',definition,session_id='author',run_id='tests-1',approved=True)
        pi_usage.configure(self.root,tokens=1000,calls=10,approved=True)

    def observed_review(self, call='review-1', **context):
        value=dict(session='reviewer',role='reviewer',phase='review',provider='fixture',model='fixture',
                   candidate=self.candidate['id'],change_id='change-1')
        value.update(context)
        pi_usage.admit(self.root,call,value)
        pi_usage.record(self.root,call,dict(input=10,output=2,cacheRead=0,cacheWrite=0))
        return dict(call_id=call,decision='accept',findings=[])

    def test_observed_independent_review_allows_technical_closure_not_delivery(self):
        ticket=admission.request_review(self.root,'change-1','reviewer',approved=True)
        event=self.observed_review()
        admission.admit_review(self.root,'change-1',ticket,event)
        result=assess_candidate(self.root,'change-1')
        self.assertEqual(result['status'],'reviewed'); self.assertTrue(result['can_close'])
        self.assertFalse(result['delivery_authorized'])
        report=self.root/'aikya/docs/validation/change-1/review.md'
        self.assertTrue(report.read_text().endswith('GENERATED BY AIKYA HARNESS\n'))
        self.assertIn('validation/change-1/review.md',(self.root/'aikya/docs/indice.md').read_text())

    def test_review_language_is_bound_at_request_and_survives_later_policy_changes(self):
        from aikya.documentation.language import write_approved
        import json
        write_approved(self.root,'es')
        ticket=admission.request_review(self.root,'change-1','reviewer',approved=True)
        (self.root/'.aikya/docs-policy.json').write_text(json.dumps(dict(schema_version=1,language='en')))
        event=self.observed_review()
        admission.admit_review(self.root,'change-1',ticket,event)
        report=(self.root/'aikya/docs/validation/change-1/review.md').read_text()
        self.assertTrue(report.startswith('# Revisión independiente'))
        self.assertEqual(report.count('GENERATED BY AIKYA HARNESS'),1)
        self.assertTrue(assess_candidate(self.root,'change-1')['can_close'])
        admission.admit_review(self.root,'change-1',ticket,event)
        self.assertEqual((self.root/'aikya/docs/validation/change-1/review.md').read_text(),report)

    def test_self_review_and_unobserved_json_cannot_approve(self):
        with self.assertRaises(ValueError): admission.request_review(self.root,'change-1','author',approved=True)
        ticket=admission.request_review(self.root,'change-1','reviewer',approved=True)
        with self.assertRaises(ValueError): admission.admit_review(self.root,'change-1',ticket,dict(call_id='fake',decision='accept',findings=[]))
        self.assertFalse(assess_candidate(self.root,'change-1')['can_close'])

    def test_duplicate_is_idempotent_conflicting_replay_and_tampering_are_refused(self):
        ticket=admission.request_review(self.root,'change-1','reviewer',approved=True); event=self.observed_review()
        first=admission.admit_review(self.root,'change-1',ticket,event)
        self.assertEqual(admission.admit_review(self.root,'change-1',ticket,event),first)
        with self.assertRaises(ValueError): admission.admit_review(self.root,'change-1',ticket,{**event,'decision':'escalate'})
        path=self.root/'aikya/docs/validation/change-1/review.json'
        path.write_text(path.read_text().replace('accept','reject'))
        self.assertFalse(assess_candidate(self.root,'change-1')['can_close'])

    def test_source_drift_and_other_candidate_review_are_rejected(self):
        ticket=admission.request_review(self.root,'change-1','reviewer',approved=True)
        event=self.observed_review(candidate='0'*64)
        with self.assertRaises(ValueError): admission.admit_review(self.root,'change-1',ticket,event)
        (self.root/'source.py').write_text('VALUE = 2\n')
        self.assertEqual(assess_candidate(self.root,'change-1')['status'],'stale')

    def test_high_findings_cannot_be_accepted_or_silently_authorize_fixes(self):
        ticket=admission.request_review(self.root,'change-1','reviewer',approved=True); event=self.observed_review()
        event['findings']=[dict(path='source.py',line=1,severity='high',summary='Unsafe input handling')]
        with self.assertRaises(ValueError): admission.admit_review(self.root,'change-1',ticket,event)
        event['decision']='changes_requested'; admission.admit_review(self.root,'change-1',ticket,event)
        self.assertFalse(assess_candidate(self.root,'change-1')['can_close'])
        self.assertEqual((self.root/'source.py').read_text(),'VALUE = 1\n')

    def test_successor_requires_new_checks_and_review_without_losing_history(self):
        ticket=admission.request_review(self.root,'change-1','reviewer',approved=True)
        event=self.observed_review(); event['decision']='changes_requested'
        admission.admit_review(self.root,'change-1',ticket,event)
        previous=self.candidate
        (self.root/'source.py').write_text('VALUE = 2\n')
        self.candidate=freeze_candidate(self.root,'change-1',['source.py'],session_id='author',parent=previous['id'],policy=previous['policy'])
        store_candidate(self.root,self.candidate,approved=True)
        with self.assertRaises(ValueError): admission.request_review(self.root,'change-1','reviewer',approved=True)
        run_check(self.root,'change-1',self.definition,session_id='author',run_id='tests-2',approved=True)
        successor=admission.request_review(self.root,'change-1','reviewer',approved=True)
        admission.admit_review(self.root,'change-1',successor,self.observed_review(call='review-2'))
        self.assertTrue(assess_candidate(self.root,'change-1')['can_close'])
        self.assertEqual(len(list((self.root/'aikya/docs/validation/change-1/reviews').glob('*/review.json'))),2)

    def test_one_observed_call_cannot_be_reused_for_a_second_review_ticket(self):
        first=admission.request_review(self.root,'change-1','reviewer',approved=True)
        second=admission.request_review(self.root,'change-1','reviewer',approved=True)
        event=self.observed_review(); admission.admit_review(self.root,'change-1',first,event)
        with self.assertRaises(ValueError): admission.admit_review(self.root,'change-1',second,event)


if __name__=='__main__': unittest.main()
