"""Selected native skills are immutable reviewed data, never automatic executable code."""
import importlib
from pathlib import Path
import tempfile
import unittest
try:skills=importlib.import_module('aikya.services.selected_skills')
except ModuleNotFoundError:skills=None


class SelectedSkillsTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(skills,'Native selected-skill service is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.base=Path(self.tmp.name).resolve();self.root=self.base/'project';self.root.mkdir()
        self.source=self.base/'example-skill';self.source.mkdir()
        (self.source/'SKILL.md').write_text('---\nname: example-skill\ndescription: Explain the selected project conventions\nallowed-tools: Bash\n---\nUse the selected conventions. See references/guide.md.\n')
        (self.source/'references').mkdir();(self.source/'references/guide.md').write_text('# Local guide\n\nReviewed local conventions.\n')

    def preview(self):return skills.preview(self.root,str(self.source))

    def install(self):
        plan=self.preview()['plan']
        with self.assertRaises(ValueError):skills.apply(self.root,plan)
        return skills.apply(self.root,plan,approved=True)

    def test_registry_capacity_is_checked_before_package_or_document_effects(self):
        from hashlib import sha256
        def observed():
            return {p.relative_to(self.root).as_posix():sha256(p.read_bytes()).hexdigest() for p in self.root.rglob('*') if p.is_file()}
        refused=False
        for number in range(20):
            source=self.base/('bounded-skill-'+str(number));source.mkdir()
            (source/'SKILL.md').write_text('---\nname: '+source.name+'\ndescription: Bounded explicit resource library\n---\nUse only selected resources.\n')
            for index in range(79):(source/('r-'+str(index).zfill(2)+'-abcdefgh.txt')).write_text('Resource data')
            before=observed()
            try:
                value=skills.preview(self.root,str(source));skills.apply(self.root,value['plan'],approved=True)
            except ValueError:
                refused=True;self.assertEqual(observed(),before,'Capacity failure left package or documentation effects');break
            self.assertEqual(len(skills.resolve(self.root)['skills']),number+1,'A successful install produced an unreadable registry')
        self.assertTrue(refused,'Bounded registry capacity was never enforced')

    def test_an_unknown_generated_audit_at_the_planned_path_is_preserved_before_copy(self):
        plan=self.preview()['plan'];operation=Path(plan['reservation']).stem
        audit=self.root/'aikya/docs/operations'/('skill-install-'+operation+'.md');audit.parent.mkdir(parents=True)
        raw='# Existing generated record\n\nPreserve user data.\n\nGENERATED BY AIKYA HARNESS\n';audit.write_text(raw)
        with self.assertRaises(ValueError):skills.apply(self.root,plan,approved=True)
        self.assertEqual(audit.read_text(),raw);self.assertFalse((self.root/plan['destination']).exists())
        self.assertEqual(skills.resolve(self.root)['skills'],[])

    def test_combined_cache_resource_path_is_refused_during_read_only_preview(self):
        path=self.source/'references'/('x'*135+'.md');path.write_text('A valid source name that exceeds the target cache path bound.')
        with self.assertRaises(ValueError):self.preview()
        self.assertEqual(list(self.root.iterdir()),[])

    def test_planning_and_empty_status_are_read_only(self):
        self.assertEqual(skills.status(self.root)['skills'],[])
        value=self.preview();self.assertIn('Use the selected conventions.',value['review']['content'])
        self.assertEqual(value['review']['name'],'example-skill')
        self.assertIn('allowed-tools',value['review']['ignored_fields'])
        self.assertEqual(list(self.root.iterdir()),[])

    def test_approved_install_is_project_local_stamped_indexed_and_never_executes(self):
        (self.source/'script.py').write_text('raise RuntimeError("MUST NOT EXECUTE")\n')
        before=(self.source/'SKILL.md').read_bytes();result=self.install()
        self.assertEqual(result['status'],'installed');self.assertTrue(result['restart_required'])
        self.assertEqual((self.source/'SKILL.md').read_bytes(),before)
        entry=skills.resolve(self.root)['skills'][0]
        copied=self.root/entry['file'];self.assertTrue(copied.read_text().endswith('GENERATED BY AIKYA HARNESS\n'))
        self.assertIn('disable-model-invocation: true',copied.read_text())
        self.assertFalse((self.root/'.claude').exists())
        comparison=self.root/'aikya/docs/tools/skill-comparison.md';self.assertTrue(comparison.exists())
        self.assertIn('tools/skill-comparison.md',(self.root/'aikya/docs/indice.md').read_text())
        with self.assertRaises(ValueError):self.install()

    def test_source_or_registry_drift_cannot_reuse_a_preview(self):
        plan=self.preview()['plan'];(self.source/'references/guide.md').write_text('New content')
        with self.assertRaises(ValueError):skills.apply(self.root,plan,approved=True)
        self.assertEqual(list(self.root.iterdir()),[])
        self.install();path=self.root/'.aikya/pi/skills/registry.json';path.write_text('{"custom":true}')
        with self.assertRaises(ValueError):skills.status(self.root)
        self.assertEqual(path.read_text(),'{"custom":true}')

    def test_reading_resources_is_bounded_current_and_cannot_escape_to_private_state(self):
        self.install()
        result=skills.read_resource(self.root,'example-skill','references/guide.md',offset=0,max_chars=512)
        self.assertIn('Reviewed local conventions.',result['content'])
        self.assertIsNone(result['next_offset'])
        for path in ('../registry.json','../../agent/auth.json','.env'):
            with self.assertRaises(ValueError):skills.read_resource(self.root,'example-skill',path,offset=0,max_chars=512)
        entry=skills.resolve(self.root)['skills'][0];(self.root/entry['file']).write_text('Changed installed instructions')
        with self.assertRaises(ValueError):skills.resolve(self.root)

    def test_symlinks_secrets_reserved_names_and_custom_documents_are_preserved(self):
        (self.source/'secret.env').symlink_to(self.source/'SKILL.md')
        with self.assertRaises(ValueError):self.preview()
        (self.source/'secret.env').unlink();(self.source/'.env').write_text('NOT_A_REAL_SECRET')
        with self.assertRaises(ValueError):self.preview()
        (self.source/'.env').unlink()
        path=self.root/'aikya/docs/tools/skill-comparison.md';path.parent.mkdir(parents=True);path.write_text('Custom comparison')
        with self.assertRaises(ValueError):self.preview()
        self.assertEqual(path.read_text(),'Custom comparison')

    def test_unknown_installed_folder_is_never_adopted(self):
        plan=self.preview()['plan'];target=self.root/plan['destination'];target.mkdir(parents=True)
        (target/'custom.txt').write_text('Preserve')
        with self.assertRaises(ValueError):skills.apply(self.root,plan,approved=True)
        self.assertEqual((target/'custom.txt').read_text(),'Preserve')

    def test_source_change_between_final_preview_and_copy_is_rejected(self):
        from unittest.mock import patch
        original=skills.snapshot;calls=0;plan=self.preview()['plan']
        def changed(source):
            nonlocal calls
            calls+=1
            if calls==3:
                path=self.source/'SKILL.md';path.write_text(path.read_text().replace('Use the selected conventions.','Unreviewed replacement instructions.'))
            return original(source)
        with patch.object(skills,'snapshot',side_effect=changed):
            with self.assertRaises(ValueError):skills.apply(self.root,plan,approved=True)
        self.assertFalse((self.root/plan['destination']).exists())

    def test_interrupted_copy_is_not_replayed_and_existing_comparison_rows_survive(self):
        from unittest.mock import patch
        path=self.root/'aikya/docs/tools/skill-comparison.md';path.parent.mkdir(parents=True)
        path.write_text('# Previous comparison\n\nKeep the previously registered skill.\n\nGENERATED BY AIKYA HARNESS\n')
        plan=self.preview()['plan']
        from aikya.services import skill_packages
        original=skill_packages.write_new
        def interrupted(target,*args,**kwargs):
            if str(target).endswith('/files/SKILL.md'):raise OSError('Interrupted package copy')
            return original(target,*args,**kwargs)
        with patch.object(skill_packages,'write_new',side_effect=interrupted):
            with self.assertRaises(OSError):skills.apply(self.root,plan,approved=True)
        with self.assertRaises(ValueError):skills.apply(self.root,plan,approved=True)
        self.assertEqual(skills.status(self.root)['skills'],[])
        self.assertIn('Keep the previously registered skill.',path.read_text())

    def test_changed_resource_or_duplicate_metadata_cannot_be_used(self):
        self.install();entry=skills.resolve(self.root)['skills'][0]
        (self.root/entry['base']/'references/guide.md').write_text('Changed after approval')
        with self.assertRaises(ValueError):skills.read_resource(self.root,'example-skill','references/guide.md',offset=0,max_chars=512)

    def test_context_bridge_reads_only_an_explicit_approved_resource_alias(self):
        self.install()
        from aikya.services.bridge import dispatch
        request=dict(schema=1,id='skill-read',project=str(self.root),operation='context',
                     arguments=dict(query='guide',paths=['@skill/example-skill/references/guide.md'],max_chars=512))
        result=dispatch(self.root,request)
        self.assertTrue(result['ok'])
        self.assertIn('Reviewed local conventions.',result['result'].get('content',''))

    def test_successful_installs_preserve_legacy_comparison_and_register_both_skills(self):
        path=self.root/'aikya/docs/tools/skill-comparison.md';path.parent.mkdir(parents=True)
        path.write_text('# Previous comparison\n\nKeep the previously registered skill.\n\nGENERATED BY AIKYA HARNESS\n')
        self.install()
        other=self.base/'second-skill';other.mkdir()
        (other/'SKILL.md').write_text('---\nname: second-skill\ndescription: Another explicit local choice\n---\nUse independently verified data.\n')
        value=skills.preview(self.root,str(other));skills.apply(self.root,value['plan'],approved=True)
        body=path.read_text();self.assertIn('Keep the previously registered skill.',body)
        self.assertIn('example-skill',body);self.assertIn('second-skill',body)
        self.assertEqual(body.count('<!-- AIKYA PI SELECTED SKILLS -->'),1)
        self.assertEqual(body.count('GENERATED BY AIKYA HARNESS'),1)
        self.assertEqual(len(skills.status(self.root)['skills']),2)

    def test_completed_initial_package_is_recoverable_without_rereading_the_source(self):
        from unittest.mock import patch
        from aikya.services import skill_packages
        plan=self.preview()['plan'];actual=skills.atomic_write
        def interrupt(path,*args,**kwargs):
            if str(path).endswith('/skills/registry.json'):raise OSError('Interrupted first registry promotion')
            return actual(path,*args,**kwargs)
        with patch.object(skills,'atomic_write',side_effect=interrupt):
            with self.assertRaises(OSError):skills.apply(self.root,plan,approved=True)
        self.assertEqual(skills.resolve(self.root)['skills'],[])
        (self.source/'SKILL.md').unlink();value=skills.recovery_preview(self.root)
        with patch.object(skill_packages,'write',side_effect=AssertionError('Never replay completed source copy')):
            skills.recover(self.root,value['plan'],approved=True)
        self.assertEqual(skills.verify(self.root,'example-skill')['source_hash'],plan['source_hash'])

    def test_package_copied_without_registry_commit_cannot_be_activated(self):
        from unittest.mock import patch
        plan=self.preview()['plan']
        with patch.object(skills,'write_document',side_effect=OSError('Interrupted audit publication')):
            with self.assertRaises(OSError):skills.apply(self.root,plan,approved=True)
        self.assertEqual(skills.resolve(self.root)['skills'],[])
        with self.assertRaises(ValueError):skills.apply(self.root,plan,approved=True)
        self.assertTrue((self.root/plan['destination']/'original.zip').is_file())

    def test_resources_outside_the_signed_manifest_cannot_be_adopted(self):
        self.install();entry=skills.resolve(self.root)['skills'][0]
        (self.root/entry['base']/'extra.md').write_text('Unapproved resource')
        with self.assertRaises(ValueError):skills.read_resource(self.root,'example-skill','extra.md',offset=0,max_chars=512)

    def test_unreadable_subdirectory_cannot_be_silently_omitted(self):
        from unittest.mock import patch
        import os
        actual=os.scandir;protected=self.source/'references'
        def deny(path):
            if not isinstance(path,int) and Path(path)==protected:raise PermissionError('Controlled inaccessible resource directory')
            return actual(path)
        with patch('os.scandir',side_effect=deny):
            with self.assertRaises((ValueError,OSError)):self.preview()
        self.assertEqual(list(self.root.iterdir()),[])

    def test_directory_discovery_has_a_budget_even_without_extra_files(self):
        for number in range(161):(self.source/('empty-'+str(number))).mkdir()
        with self.assertRaises(ValueError):self.preview()
        self.assertEqual(list(self.root.iterdir()),[])

    def test_windows_line_endings_preserve_original_bytes_and_activate_canonical_entry(self):
        path=self.source/'SKILL.md';original=path.read_bytes().replace(b'\n',b'\r\n');path.write_bytes(original)
        self.install();entry=skills.resolve(self.root)['skills'][0]
        import zipfile
        with zipfile.ZipFile((self.root/entry['base']).parent/'original.zip') as archive:self.assertEqual(archive.read('SKILL.md'),original)
        self.assertNotIn(b'\r\n',(self.root/entry['file']).read_bytes())

    def test_uppercase_markdown_resources_are_stamped_without_changing_originals(self):
        original=b'# Reference\r\n\r\nOriginal bytes.\r\n';(self.source/'REFERENCE.MD').write_bytes(original)
        self.install();entry=skills.resolve(self.root)['skills'][0]
        copied=(self.root/entry['base']/'REFERENCE.MD').read_bytes()
        self.assertTrue(copied.endswith(b'GENERATED BY AIKYA HARNESS\n'))
        import zipfile
        with zipfile.ZipFile((self.root/entry['base']).parent/'original.zip') as archive:self.assertEqual(archive.read('REFERENCE.MD'),original)


if __name__=='__main__':unittest.main()
