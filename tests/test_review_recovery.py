"""Recovery publishes known observations and never reruns uncertain effects."""
import importlib
import json
from pathlib import Path
import sys
import tempfile
import unittest
from aikya.review.candidates import freeze_candidate,store_candidate,is_current
from aikya.review.executor import run_check,check_binding
from aikya.review.receipts import load_receipts
try: recovery=importlib.import_module('aikya.review.recovery')
except ModuleNotFoundError: recovery=None


class RecoveryTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(recovery,'Read-only reconciliation is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name).resolve();(self.root/'source.py').write_text('VALUE = 1\n')
        script='import os;from pathlib import Path;Path(os.environ["AIKYA_TEST_REPORT"]).write_text(\'<testsuite tests="1"><testcase name="ok"/></testsuite>\')'
        self.definition=dict(name='tests',argv=[sys.executable,'-I','-B','-c',script],cwd='.',report_format='junit',timeout_seconds=3,max_output_bytes=65536)
        self.candidate=freeze_candidate(self.root,'change-1',['source.py'],session_id='author',
            policy=dict(checks=['tests'],review_required=True,definitions={'tests':check_binding(self.root,self.definition)}))
        store_candidate(self.root,self.candidate,approved=True)

    def test_completed_observation_is_recoverable_without_spawning_a_process(self):
        result=run_check(self.root,'change-1',self.definition,session_id='author',run_id='one',approved=True)
        journal=self.root/'aikya/docs/validation/change-1/receipts.jsonl';journal.unlink()
        before={p.relative_to(self.root):p.read_bytes() for p in self.root.rglob('*') if p.is_file()}
        plan=recovery.plan_reconciliation(self.root,'change-1')
        self.assertEqual(plan['attempts'][0]['action'],'attach_observation')
        self.assertEqual(before,{p.relative_to(self.root):p.read_bytes() for p in self.root.rglob('*') if p.is_file()})
        with self.assertRaises(ValueError): recovery.recover_execution(self.root,'change-1','one')
        recovery.recover_execution(self.root,'change-1','one',approved=True)
        self.assertEqual(len(load_receipts(self.root,'change-1')),1)
        self.assertEqual(load_receipts(self.root,'change-1')[0]['payload']['evidence'],result['evidence'])

    def test_pending_attempt_remains_manual_and_cannot_be_promoted_by_a_report(self):
        path=self.root/'aikya/docs/validation/change-1/checks/pending/execution.json';path.parent.mkdir(parents=True)
        path.write_text(json.dumps(dict(schema=1,generated_by='aikya-check-executor',status='pending',check='tests')))
        (path.parent/'report.xml').write_text('<testsuite tests="1"><testcase name="fake"/></testsuite>')
        self.assertEqual(recovery.plan_reconciliation(self.root,'change-1')['attempts'][0]['action'],'manual_reconciliation')
        with self.assertRaises(ValueError): recovery.recover_execution(self.root,'change-1','pending',approved=True)
        self.assertEqual(load_receipts(self.root,'change-1'),[])

    def test_only_canonical_document_index_is_derived_source(self):
        index=self.root/'aikya/docs/indice.md';index.write_text('# Document index\n\nGENERATED BY AIKYA HARNESS\n')
        candidate=freeze_candidate(self.root,'change-2',['source.py'],session_id='author')
        index.write_text('# Document index\n\n- [a.md](a.md)\n\nGENERATED BY AIKYA HARNESS\n')
        self.assertTrue(is_current(self.root,candidate))
        index.write_text('# Document index\n\nUser requirements\n\nGENERATED BY AIKYA HARNESS\n')
        custom=freeze_candidate(self.root,'change-3',['source.py'],session_id='author')
        index.write_text(index.read_text().replace('requirements','changed requirements'))
        self.assertFalse(is_current(self.root,custom))


if __name__=='__main__': unittest.main()
