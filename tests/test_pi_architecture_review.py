"""Native architecture findings are explicit interpretations of verified source excerpts."""
import importlib,json,tempfile,unittest
from pathlib import Path
from unittest.mock import patch
try:native=importlib.import_module('aikya.services.engineering_workflows')
except ModuleNotFoundError:native=None

class ArchitectureReviewTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(native,'Native engineering workflows are absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        (self.root/'.harness').mkdir();(self.root/'.harness/project-profile.json').write_text(json.dumps(dict(decisions=dict(backend='python',methodology='odd',mode='existing'))))
        (self.root/'service.py').write_text('class Service:\n    def value(self):\n        return 1\n')
        self.data=dict(action='record',title='Selected architecture',paths=['service.py'],findings=[dict(path='service.py',line=1,end_line=1,quote='class Service:',kind='observation',severity='info',message='A service class is declared.')])
    def preview(self,data=None):return native.preview(self.root,'aikya-arc-review',data or self.data,'author-session')
    def test_inspection_is_bounded_read_only_and_never_claims_runtime_verification(self):
        value=self.preview(dict(action='inspect',paths=['service.py'],query='Service',max_chars=1000))
        self.assertIsNone(value['plan']);self.assertEqual(value['status'],'context_ready')
        self.assertIn('Service',value['review']['context']['context'][0]['text'])
        self.assertEqual(value['review']['runtime'],'not_verified');self.assertFalse((self.root/'aikya').exists())
    def test_confirmed_record_reuses_architecture_template_and_preserves_sections(self):
        from aikya.documentation.layout import write_document
        write_document(self.root,'architecture/architecture-overview.md','# Existing architecture\n\n## 3. Constraints\n\nKeep the public API.\n')
        value=self.preview()
        with self.assertRaises(ValueError):native.apply(self.root,value['plan'])
        result=native.apply(self.root,value['plan'],approved=True)
        self.assertEqual(result['status'],'documents_recorded')
        path=self.root/'aikya/docs/architecture/architecture-overview.md';body=path.read_text()
        self.assertIn('Keep the public API.',body);self.assertIn('service.py',body);self.assertIn('class Service:',body)
        self.assertEqual(body.splitlines().count('GENERATED BY AIKYA HARNESS'),1)
        self.assertFalse(result['delivery_authorized']);self.assertFalse((self.root/'.claude').exists())
    def test_unanchored_findings_private_paths_and_invalid_lines_are_refused(self):
        for change in (dict(quote='invented'),dict(line=9,end_line=9),dict(path='other.py'),dict(kind='runtime_verified')):
            with self.subTest(change=change),self.assertRaises(ValueError):self.preview({**self.data,'findings':[{**self.data['findings'][0],**change}]})
        with self.assertRaises(ValueError):self.preview(dict(action='inspect',paths=['.aikya/private.json'],query='',max_chars=1000))
        self.assertFalse((self.root/'aikya').exists())
    def test_source_locale_or_custom_document_drift_preserves_owner_data(self):
        value=self.preview();(self.root/'service.py').write_text('class Other: pass\n')
        with self.assertRaises(ValueError):native.apply(self.root,value['plan'],approved=True)
        path=self.root/'aikya/docs/architecture/architecture-overview.md';path.parent.mkdir(parents=True);path.write_text('OWNER PAGE\n')
        (self.root/'service.py').write_text('class Service:\n    pass\n')
        with self.assertRaises(ValueError):self.preview()
        self.assertEqual(path.read_text(),'OWNER PAGE\n')
    def test_sources_changed_between_excerpt_capture_and_document_preview_are_refused(self):
        from aikya.services import documentation
        original=documentation.preview
        def changed(*args,**kwargs):
            (self.root/'service.py').write_text('class Service:\n    VALUE = 9\n')
            return original(*args,**kwargs)
        with patch.object(documentation,'preview',side_effect=changed),self.assertRaises(ValueError):self.preview()
