"""Project version replacement preserves prior choices and never replays uncertain package writes."""
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from aikya.services import selected_skills as skills,skill_packages
from aikya.storage import atomic_write


class ProjectChangesTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.base=Path(self.tmp.name).resolve()
        self.root=self.base/'project';self.root.mkdir();self.source=self.base/'example-skill';self.source.mkdir()
        self.original='---\nname: example-skill\ndescription: Selected conventions\n---\nOriginal instructions.\n'
        (self.source/'SKILL.md').write_text(self.original)
        value=skills.preview(self.root,str(self.source));skills.apply(self.root,value['plan'],approved=True)
        self.first=skills.verify(self.root,'example-skill')
        self.assertTrue(callable(getattr(skills,'change_preview',None)),'Project skill update and rollback are absent')

    def proposal(self):
        (self.source/'SKILL.md').write_text(self.original+'Updated instructions.\n')
        return skills.change_preview(self.root,action='update',source=str(self.source))

    def test_update_and_rollback_retain_exact_previous_package_and_require_confirmation(self):
        value=self.proposal();self.assertEqual(value['review']['before'],self.first['source_hash'])
        with self.assertRaises(ValueError):skills.apply(self.root,value['plan'])
        self.assertEqual(skills.verify(self.root,'example-skill'),self.first)
        skills.apply(self.root,value['plan'],approved=True);second=skills.verify(self.root,'example-skill')
        self.assertNotEqual(second['body_hash'],self.first['body_hash'])
        self.assertEqual((self.root/self.first['file']).read_bytes().split(b'---\n',2)[2].split(b'GENERATED')[0].strip(),b'Original instructions.')
        undo=skills.change_preview(self.root,action='rollback',name='example-skill',source_hash=self.first['source_hash'])
        result=skills.apply(self.root,undo['plan'],approved=True);self.assertTrue(result['restart_required'])
        self.assertEqual(skills.verify(self.root,'example-skill'),self.first)

    def test_only_recorded_retained_versions_can_be_restored_and_customized_data_survives(self):
        value=self.proposal();skills.apply(self.root,value['plan'],approved=True)
        with self.assertRaises(ValueError):skills.change_preview(self.root,action='rollback',name='example-skill',source_hash='f'*64)
        target=self.root/self.first['file'];target.write_text('Customized old instructions')
        with self.assertRaises(ValueError):skills.change_preview(self.root,action='rollback',name='example-skill',source_hash=self.first['source_hash'])
        self.assertEqual(target.read_text(),'Customized old instructions')

    def test_unknown_generated_change_audit_is_not_overwritten_or_adopted(self):
        from aikya.review.contracts import digest
        value=self.proposal();audit=self.root/'aikya/docs/operations'/('skill-change-'+digest(value['plan'])+'.md')
        raw='# Existing generated report\n\nKeep it.\n\nGENERATED BY AIKYA FORGE\n';audit.write_text(raw)
        with self.assertRaises(ValueError):skills.apply(self.root,value['plan'],approved=True)
        self.assertEqual(audit.read_text(),raw);self.assertEqual(skills.verify(self.root,'example-skill'),self.first)
        self.assertFalse((self.root/value['plan']['destination']).exists())

    def test_failed_copy_preserves_active_version_and_blocks_new_mutation_until_review(self):
        value=self.proposal()
        with patch.object(skill_packages,'write',side_effect=OSError('Interrupted copy')):
            with self.assertRaises(OSError):skills.apply(self.root,value['plan'],approved=True)
        self.assertEqual(skills.verify(self.root,'example-skill'),self.first)
        self.assertEqual(skills.status(self.root).get('status'),'pending')
        with self.assertRaises(ValueError):skills.change_preview(self.root,action='update',source=str(self.source))
        with self.assertRaises(ValueError):skills.recovery_preview(self.root)

    def test_complete_copy_recovery_promotes_without_source_or_package_replay(self):
        value=self.proposal();actual=skills.atomic_write
        def interrupt(path,*a,**kw):
            if str(path).endswith('/skills/registry.json'):raise OSError('Before registry promotion')
            return actual(path,*a,**kw)
        with patch.object(skills,'atomic_write',side_effect=interrupt):
            with self.assertRaises(OSError):skills.apply(self.root,value['plan'],approved=True)
        self.assertEqual(skills.verify(self.root,'example-skill'),self.first)
        (self.source/'SKILL.md').unlink();recover=skills.recovery_preview(self.root)
        with self.assertRaises(ValueError):skills.recover(self.root,recover['plan'])
        with patch.object(skill_packages,'write',side_effect=AssertionError('No package replay')):
            skills.recover(self.root,recover['plan'],approved=True)
        self.assertEqual(skills.verify(self.root,'example-skill')['source_hash'],value['plan']['source_hash'])
        self.assertEqual((self.root/'aikya/docs/tools/skill-comparison.md').read_text().count('GENERATED BY AIKYA FORGE'),1)

    def test_changed_comparison_after_interruption_is_preserved_and_cannot_be_recovered(self):
        value=self.proposal()
        with patch.object(skills,'write_document',side_effect=OSError('Before documentation')):
            with self.assertRaises(OSError):skills.apply(self.root,value['plan'],approved=True)
        comparison=self.root/'aikya/docs/tools/skill-comparison.md';comparison.write_text('Customized after interruption')
        with self.assertRaises(ValueError):skills.recovery_preview(self.root)
        self.assertEqual(comparison.read_text(),'Customized after interruption')
        self.assertEqual(skills.verify(self.root,'example-skill'),self.first)


if __name__=='__main__':unittest.main()
