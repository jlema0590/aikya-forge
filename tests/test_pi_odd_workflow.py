"""Native ODD completion needs current task scope and independently reviewed checks."""
import importlib
import json
from pathlib import Path
import sys
import tempfile
import unittest
from aikya.installation import portable
from aikya.workflows import odd
from aikya.services import authorization,checks
try:native=importlib.import_module('aikya.services.odd_workflow')
except ModuleNotFoundError:native=None


class PiOddWorkflowTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(native,'Native ODD host workflow is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name).resolve()
        profile=dict(backend='python',methodology='odd',repository_layout='singlerepo',mode='new')
        portable.apply(self.root,portable.preview(self.root,profile,language='es'),approved=True)
        (self.root/'value.py').write_text('VALUE=0\n')
        (self.root/'test.py').write_text('from pathlib import Path\nok="VALUE=1" in Path("value.py").read_text()\nprint("TAP version 13")\nprint("1..1")\nprint(("ok" if ok else "not ok")+" 1 - expected value")\nraise SystemExit(0 if ok else 1)\n')
        self.raw=dict(title='Expected value',objective='Return the expected value',acceptance=['The value is one'],
            facts=dict(understood=False,contained_risk=True,resumable_from_request_diff=True),
            tasks=[dict(id='TASK-001',description='Return one',acceptance=['AC-01'],depends_on=[],files=['value.py','test.py'],checks=['tests'])])

    def prepare(self):
        plan=native.preview(self.root,'create',dict(feature_id='expected-value',input_data=self.raw),session_id='author')
        self.assertEqual(plan['detail'].get('paths'),['aikya/docs/features/expected-value/spec.md','aikya/docs/features/expected-value/state.json','aikya/docs/indice.md'])
        with self.assertRaises(ValueError):native.apply(self.root,plan)
        return native.apply(self.root,plan,approved=True)

    def bind(self):
        plan=native.preview(self.root,'bind',dict(feature_id='expected-value',task_id='TASK-001'),session_id='author')
        return native.apply(self.root,plan,approved=True)

    def test_substantial_uses_canonical_localized_dossier_and_small_work_has_no_dossier(self):
        small={**self.raw,'facts':dict(understood=True,contained_risk=True,resumable_from_request_diff=True)}
        plan=native.preview(self.root,'create',dict(feature_id='small',input_data=small),session_id='author')
        result=native.apply(self.root,plan,approved=True)
        self.assertEqual(result['tracking'],'request');self.assertFalse((self.root/'aikya/docs/features/small').exists())
        self.prepare();doc=self.root/'aikya/docs/features/expected-value/spec.md'
        self.assertTrue(doc.exists());self.assertEqual(doc.read_text().count('GENERATED BY AIKYA FORGE'),1)
        self.assertEqual(odd.load(self.root,'expected-value')['docs_language'],'es')
        self.assertFalse((self.root/'.claude').exists())

    def test_source_drift_approval_or_unknown_metadata_cannot_write(self):
        plan=native.preview(self.root,'create',dict(feature_id='expected-value',input_data=self.raw),session_id='author')
        (self.root/'value.py').write_text('VALUE=2\n')
        with self.assertRaises(ValueError):native.apply(self.root,plan,approved=True)
        self.assertFalse((self.root/'aikya/docs/features/expected-value').exists())
        self.prepare();self.bind()
        target=self.root/'.aikya/pi/odd-workflow.json';target.write_text('{"custom":true}')
        with self.assertRaises(ValueError):self.bind()
        self.assertEqual(target.read_text(),'{"custom":true}')

    def test_profile_drift_invalidates_a_preview(self):
        plan=native.preview(self.root,'create',dict(feature_id='expected-value',input_data=self.raw),session_id='author')
        profile=self.root/'.harness/project-profile.json';raw=json.loads(profile.read_text())
        raw['decisions']['backend']='java';profile.write_text(json.dumps(raw))
        with self.assertRaises(ValueError):native.apply(self.root,plan,approved=True)
        self.assertFalse((self.root/'aikya/docs/features/expected-value').exists())

    def test_replaced_task_selection_invalidates_a_preview(self):
        self.prepare()
        plan=native.preview(self.root,'bind',dict(feature_id='expected-value',task_id='TASK-001'),session_id='author')
        self.bind()
        original=(self.root/'.aikya/pi/odd-workflow.json').read_bytes()
        with self.assertRaises(ValueError):native.apply(self.root,plan,approved=True)
        self.assertEqual((self.root/'.aikya/pi/odd-workflow.json').read_bytes(),original)

    def test_binding_limits_writes_by_task_session_and_current_state(self):
        self.prepare();self.bind();intent=dict(path='value.py',content='VALUE=1\n')
        self.assertIsNotNone(authorization.preview(self.root,intent,session='author')['workflow_revision'])
        with self.assertRaises(ValueError):authorization.preview(self.root,intent,session='other')
        (self.root/'outside.py').write_text('VALUE=0\n')
        with self.assertRaises(ValueError):authorization.preview(self.root,dict(path='outside.py',content='VALUE=1\n'),session='author')
        odd.advance_task(self.root,'expected-value','TASK-001','blocked',[],1)
        with self.assertRaises(ValueError):authorization.preview(self.root,intent,session='author')
        plan=native.preview(self.root,'release',{},session_id='author')
        native.apply(self.root,plan,approved=True)
        self.assertIsNone(authorization.preview(self.root,intent,session='author')['workflow_revision'])

    def test_rebinding_revokes_a_prior_host_write_grant(self):
        self.prepare();self.bind()
        intent=dict(path='value.py',content='VALUE=1\n');key=b'x'*32
        grant=authorization.issue(self.root,'author',intent,key)
        self.bind()
        with self.assertRaises(ValueError):authorization.apply_write(self.root,'author',intent,grant,key)
        self.assertEqual((self.root/'value.py').read_text(),'VALUE=0\n')

    def test_sdd_cannot_be_replaced_by_an_odd_feature(self):
        path=self.root/'.harness/project-profile.json';profile=json.loads(path.read_text())
        profile['decisions']['methodology']='sdd';path.write_text(json.dumps(profile))
        with self.assertRaises(ValueError):native.preview(self.root,'create',dict(feature_id='expected-value',input_data=self.raw),session_id='author')
        self.assertFalse((self.root/'aikya/docs/features/expected-value').exists())

    def test_cannot_complete_from_a_test_claim_or_another_session(self):
        self.prepare();self.bind()
        args=dict(feature_id='expected-value',task_id='TASK-001',change_id='unobserved')
        with self.assertRaises(ValueError):native.preview(self.root,'complete',args,session_id='author')
        with self.assertRaises(ValueError):native.preview(self.root,'complete',args,session_id='other')
        self.assertEqual(odd.load(self.root,'expected-value')['tasks'][0]['status'],'todo')

    def reviewed_change(self,objective="Return one",check_name="tests"):
        self.prepare();bound=self.bind()
        definition=dict(name=check_name,argv=[sys.executable,'-I','-B','test.py'],cwd='.',report_format='tap',timeout_seconds=3,max_output_bytes=65536)
        args=dict(change_id='task-proof',session_id='author',scope=['value.py','test.py'],definitions=[definition],
                  objective=objective,acceptance=['The value is one'],tdd_paths=['test.py'])
        checks.apply_snapshot(self.root,checks.preview_snapshot(self.root,**args),approved=True)
        red=checks.execute_iteration(self.root,checks.iteration_preview(self.root,'task-proof',check_name,'author','red'),approved=True)
        self.assertEqual(red['status'],'failed')
        (self.root/'value.py').write_text('VALUE=1\n')
        green=checks.execute_iteration(self.root,checks.iteration_preview(self.root,'task-proof',check_name,'author','green'),approved=True)
        self.assertEqual(green['assessment']['status'],'review_required')
        from aikya.review import admission
        from aikya.routing import pi_usage
        from aikya.review.candidates import load_candidate
        candidate=load_candidate(self.root,'task-proof')
        self.assertEqual(candidate['policy']['workflow_revision'],bound['workflow_revision'])
        complete=dict(feature_id='expected-value',task_id='TASK-001',change_id='task-proof')
        with self.assertRaises(ValueError):native.preview(self.root,'complete',complete,session_id='author')
        pi_usage.configure(self.root,tokens=1000,calls=10,approved=True)
        ticket=admission.request_review(self.root,'task-proof','reviewer',approved=True)
        pi_usage.admit(self.root,'review-call',dict(session='reviewer',role='reviewer',phase='review',provider='fixture',model='fixture',candidate=candidate['id'],change_id='task-proof'))
        pi_usage.record(self.root,'review-call',dict(input=10,output=2,cacheRead=0,cacheWrite=0))
        admission.admit_review(self.root,'task-proof',ticket,dict(call_id='review-call',decision='accept',findings=[]))
        return complete

    def test_actual_red_green_and_independent_admission_can_record_the_selected_task(self):
        complete=self.reviewed_change()
        plan=native.preview(self.root,'complete',complete,session_id='author')
        result=native.apply(self.root,plan,approved=True)
        self.assertEqual(result['status'],'task_recorded');self.assertFalse(result['delivery_authorized'])
        self.assertEqual(odd.load(self.root,'expected-value')['tasks'][0]['status'],'done')
        with self.assertRaises(ValueError):native.apply(self.root,plan,approved=True)

    def test_independently_reviewed_but_different_intent_cannot_complete_this_task(self):
        complete=self.reviewed_change(objective='Another objective')
        with self.assertRaises(ValueError):native.preview(self.root,'complete',complete,session_id='author')
        self.assertEqual(odd.load(self.root,'expected-value')['tasks'][0]['status'],'todo')

    def test_independently_reviewed_but_different_checks_cannot_complete_this_task(self):
        complete=self.reviewed_change(check_name='other-check')
        with self.assertRaises(ValueError):native.preview(self.root,'complete',complete,session_id='author')
        self.assertEqual(odd.load(self.root,'expected-value')['tasks'][0]['status'],'todo')

    def test_changed_review_report_during_recording_cannot_leave_a_completed_task(self):
        from unittest.mock import patch
        complete=self.reviewed_change()
        plan=native.preview(self.root,'complete',complete,session_id='author')
        original=odd.advance_task
        def changed(*args,**kwargs):
            (self.root/'aikya/docs/validation/task-proof/review.md').write_text('Changed after approval')
            return original(*args,**kwargs)
        with patch.object(odd,'advance_task',side_effect=changed):
            with self.assertRaises(ValueError):native.apply(self.root,plan,approved=True)
        self.assertEqual(odd.load(self.root,'expected-value')['tasks'][0]['status'],'blocked')

    def test_uncertain_completion_is_preserved_and_cannot_automatically_replay(self):
        from unittest.mock import patch
        complete=self.reviewed_change()
        plan=native.preview(self.root,'complete',complete,session_id='author')
        with patch.object(odd,'advance_task',side_effect=OSError('Interrupted metadata write')):
            with self.assertRaises(OSError):native.apply(self.root,plan,approved=True)
        with self.assertRaises(ValueError):native.apply(self.root,plan,approved=True)
        self.assertEqual(odd.load(self.root,'expected-value')['tasks'][0]['status'],'todo')

    def test_reconciliation_invalidates_changed_outcomes_and_preserves_custom_documents(self):
        complete=self.reviewed_change()
        native.apply(self.root,native.preview(self.root,'complete',complete,session_id='author'),approved=True)
        (self.root/'value.py').write_text('VALUE=2\n')
        plan=native.preview(self.root,'reconcile',dict(feature_id='expected-value',revision=2),session_id='author')
        native.apply(self.root,plan,approved=True)
        self.assertEqual(odd.load(self.root,'expected-value')['tasks'][0]['status'],'todo')
        doc=self.root/'aikya/docs/features/expected-value/spec.md';doc.write_text('Custom document')
        with self.assertRaises(ValueError):native.preview(self.root,'reconcile',dict(feature_id='expected-value',revision=3),session_id='author')
        self.assertEqual(doc.read_text(),'Custom document')


if __name__=='__main__':unittest.main()
