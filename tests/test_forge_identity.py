"""Forge artifacts remain installable while known legacy documents stay readable."""
from pathlib import Path
import tempfile
import unittest
import zipfile

from aikya.documentation import layout
from aikya.installation.bootstrap.environment import verify_wheel


class ForgeIdentityTests(unittest.TestCase):
    def test_python_bootstrap_preview_accepts_the_independent_forge_version_series(self):
        from aikya.installation.bootstrap import options
        with tempfile.TemporaryDirectory() as folder:
            args=options.parser().parse_args(['install','--version','0.1.0','--dry-run'])
            result=options.preview(args,Path(folder)/'application',None)
            self.assertEqual(result['version'],'0.1.0')
            self.assertFalse(result['writes']);self.assertFalse(result['network'])
            self.assertFalse((Path(folder)/'application').exists())

    def test_current_forge_wheel_is_accepted_and_legacy_identity_is_version_bounded(self):
        with tempfile.TemporaryDirectory() as folder:
            wheel = Path(folder) / 'core.whl'
            for name, version, accepted in (
                ('aikya-forge', '0.1.0', True),
                ('aikya-harness', '7.2.2', True),
                ('aikya-harness', '8.0.0a0', True),
                ('aikya-harness', '0.1.0', False),
                ('foreign', '0.1.0', False),
            ):
                with self.subTest(name=name, version=version):
                    with zipfile.ZipFile(wheel, 'w') as archive:
                        archive.writestr('core.dist-info/METADATA', f'Name: {name}\nVersion: {version}\n')
                    if accepted:
                        verify_wheel(wheel, version)
                    else:
                        with self.assertRaises(ValueError):
                            verify_wheel(wheel, version)
                    with self.assertRaises(ValueError):
                        verify_wheel(wheel, '99.0.0')

    def test_legacy_footer_is_replaced_once_and_current_content_survives(self):
        old = '# Recorded decision\n\nKeep the approved decision.\n\nGENERATED BY AIKYA HARNESS\n'
        expected = '# Recorded decision\n\nKeep the approved decision.\n\nGENERATED BY AIKYA FORGE\n'
        self.assertEqual(layout.stamp(old), expected)
        self.assertEqual(layout.stamp(expected), expected)
        self.assertTrue(layout.generated(old))
        self.assertTrue(layout.generated(expected))

    def test_legacy_index_can_refresh_but_personal_navigation_is_protected(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder).resolve()
            index = root / 'aikya/docs/indice.md'
            index.parent.mkdir(parents=True)
            index.write_text('# Document index\n\nGENERATED BY AIKYA HARNESS\n')
            layout.write_document(root, 'decisions/forge.md', '# Decision\n\nReviewed source decision.')
            self.assertIn('decisions/forge.md', index.read_text())
            self.assertTrue(index.read_text().endswith('GENERATED BY AIKYA FORGE\n'))
            custom = '# Team navigation\n\nKeep this team-owned content.\n\nGENERATED BY AIKYA HARNESS\n'
            index.write_text(custom)
            with self.assertRaises(ValueError):
                layout.write_document(root, 'decisions/other.md', '# Other\n\nAnother decision.')
            self.assertEqual(index.read_text(), custom)
            self.assertFalse((index.parent / 'decisions/other.md').exists())

    def test_reference_memories_from_the_old_footer_remain_recallable(self):
        from aikya.memory import knowledge
        with tempfile.TemporaryDirectory() as folder:
            root=Path(folder).resolve();(root/'module.py').write_text('def lookup(): return 1\n')
            note=knowledge.remember(root,dict(kind='project',text='Lookup uses the local catalog.',source='module.py',ttl_days=30),approved=True,now=100)
            path=root/note;path.write_text(path.read_text().replace('GENERATED BY AIKYA FORGE','GENERATED BY AIKYA HARNESS'))
            index=root/'aikya/docs/memory/MEMORY.md'
            index.write_text(index.read_text().replace('GENERATED BY AIKYA FORGE','GENERATED BY AIKYA HARNESS'))
            self.assertIn('Lookup uses the local catalog.',knowledge.recall(root,'Lookup',4000,now=101))
            self.assertEqual(knowledge.remember(root,dict(kind='project',text='Lookup uses the local catalog.',source='module.py',ttl_days=30),approved=True,now=101),note)


if __name__ == '__main__':
    unittest.main()
