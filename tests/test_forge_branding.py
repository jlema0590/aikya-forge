"""Canonical Forge identity with conservative recognition of generated documents."""
from pathlib import Path
import unittest
from aikya.documentation import layout


class ForgeBrandingTests(unittest.TestCase):
    def test_new_stamps_use_forge_and_replace_a_previous_footer_once(self):
        old='# Decision\n\nKeep the verified boundary.\n\nGENERATED BY AIKYA HARNESS\n'
        stamped=layout.stamp(old)
        self.assertTrue(stamped.endswith('GENERATED BY AIKYA FORGE\n'))
        self.assertNotIn('GENERATED BY AIKYA HARNESS',stamped)
        self.assertEqual(stamped.count('GENERATED BY AIKYA FORGE'),1)
        self.assertEqual(layout.content(stamped),'# Decision\n\nKeep the verified boundary.')

    def test_old_derived_index_can_be_refreshed_but_custom_prose_is_preserved(self):
        old=b'# Document index\n\n- [overview.md](overview.md)\n\nGENERATED BY AIKYA HARNESS\n'
        self.assertTrue(layout.derived_index(old))
        custom=old.replace(b'- [overview.md](overview.md)',b'Team-owned navigation text')
        self.assertFalse(layout.derived_index(custom))

    def test_existing_reference_memory_is_readable_after_footer_change(self):
        import tempfile
        from agent_loop_support import project
        from aikya.memory import knowledge
        with tempfile.TemporaryDirectory() as temporary:
            root=project(temporary)
            name=knowledge.remember(root,{'kind':'feedback','text':'Retain the stable value lookup.','source':'src/value.py','ttl_days':30},approved=True)
            path=root/name
            path.write_text(path.read_text().replace('GENERATED BY AIKYA FORGE','GENERATED BY AIKYA HARNESS'))
            self.assertIn('Retain the stable value lookup.', knowledge.recall(root,'stable value lookup',1000))

    def test_legacy_footer_is_not_accepted_for_new_authorized_writes(self):
        import tempfile
        from aikya.services import authorization
        with tempfile.TemporaryDirectory() as temporary:
            root=Path(temporary).resolve()
            intent={'path':'report.md','content':'# Report\n\nObserved result.\n\nGENERATED BY AIKYA HARNESS\n'}
            with self.assertRaisesRegex(ValueError,'footer'):
                authorization.preview(root,intent)
            self.assertFalse((root/'report.md').exists())

    def test_branding_does_not_activate_retired_publication_workflows(self):
        root=Path(__file__).resolve().parents[1]
        for name in ('release.yml','bump-versions.yml','install-pages.yml'):
            with self.subTest(workflow=name):
                text=(root/'.github/workflows'/name).read_text()
                self.assertIn('if: ${{ false }}',text)

    def test_distribution_declares_forge(self):
        root=Path(__file__).resolve().parents[1]
        self.assertIn('name = "aikya-forge"', (root/'pyproject.toml').read_text().split('[project]',1)[1].split('[',1)[0])


if __name__=='__main__':unittest.main()
