"""Only complete host-observed document transitions may extend a review iteration."""
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch
from aikya.services import checks,documentation as docs
from aikya.services.review import context


class DocumentContinuityTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        (self.root/'.harness').mkdir();(self.root/'.harness/project-profile.json').write_text(json.dumps(
            dict(decisions=dict(backend='python',methodology='odd',mode='existing'))))
        (self.root/'value.txt').write_text('wrong')
        (self.root/'test.py').write_text('from pathlib import Path\nok=Path("value.txt").read_text()=="correct"\nprint("TAP version 13\\n1..1")\nprint(("ok" if ok else "not ok")+" 1 - value")\nraise SystemExit(0 if ok else 1)\n')
        self.args=dict(change_id='iteration',scope=['value.txt','test.py'],session_id='author',objective='Correct value',
            acceptance=['Returns correct'],tdd_paths=['test.py'],definitions=[dict(name='tests',argv=[sys.executable,'-I','-B','test.py'],
            cwd='.',report_format='tap',timeout_seconds=3,max_output_bytes=65536)])
        self.data=dict(action='write',sources=['value.txt'],documents=[dict(document='architecture',payload=dict(
            title='Observed architecture',sections={'1-purpose-and-scope':'The local value module.'}))])
        self.document='aikya/docs/architecture/architecture-overview.md'

    def snapshot(self):
        plan=checks.preview_snapshot(self.root,**self.args);checks.apply_snapshot(self.root,plan,approved=True)

    def execute_check(self,run):
        plan=checks.preview_run(self.root,'iteration','tests','author',run)
        return checks.execute(self.root,plan,approved=True)

    def write_docs(self,session='author'):
        plan=docs.preview(self.root,'aikya-docs',self.data,session)['plan']
        return docs.apply(self.root,plan,approved=True)

    def red(self):
        self.snapshot();self.assertEqual(self.execute_check('red')['status'],'failed')

    def test_observed_document_update_keeps_red_lineage_and_is_in_final_review(self):
        self.red();self.write_docs();(self.root/'value.txt').write_text('correct')
        plan=checks.refresh_preview(self.root,'iteration','author');checks.apply_snapshot(self.root,plan,approved=True)
        self.assertEqual(checks.status(self.root,'iteration')['status'],'pending_checks')
        self.execute_check('green');self.assertEqual(checks.status(self.root,'iteration')['status'],'review_required')
        packet=context(self.root,'iteration')
        observed=next(f for f in packet['files'] if f['path']==self.document)
        self.assertIn('The local value module.',observed['content'])
        self.assertIn(self.document,packet['documentation_scope'])
        self.assertFalse(checks.status(self.root,'iteration')['can_close'])

    def test_multiple_observed_updates_are_chained_and_survive_a_later_source_iteration(self):
        self.red();self.write_docs()
        self.data['documents'][0]['payload']['sections']['1-purpose-and-scope']='Updated value module.'
        self.write_docs();(self.root/'value.txt').write_text('correct');self.snapshot();self.execute_check('green')
        (self.root/'value.txt').write_text('correct\n');self.snapshot()
        # The changed value intentionally fails the regression; the final packet must
        # still carry the document that was changed earlier in the same lineage.
        packet=context(self.root,'iteration')
        self.assertIn('Updated value module.',next(f for f in packet['files'] if f['path']==self.document)['content'])

    def test_manual_document_change_and_an_unobserved_gap_are_rejected(self):
        self.red();path=self.root/self.document;path.parent.mkdir(parents=True)
        path.write_text('# Manual\n\nGENERATED BY AIKYA FORGE\n')
        with self.assertRaises(ValueError):checks.refresh_preview(self.root,'iteration','author')
        # Adopting a stamped page later cannot authorize the earlier unobserved write.
        self.write_docs()
        with self.assertRaises(ValueError):checks.refresh_preview(self.root,'iteration','author')

    def test_other_author_documentation_cannot_extend_this_author_scope(self):
        self.red();self.write_docs('other-author')
        with self.assertRaises(ValueError):checks.refresh_preview(self.root,'iteration','author')

    def test_post_operation_document_edit_invalidates_the_witness(self):
        self.red();self.write_docs();path=self.root/self.document;path.write_text(path.read_text()+'Owner edit.\n')
        with self.assertRaises(ValueError):checks.refresh_preview(self.root,'iteration','author')

    def test_methodology_control_is_not_a_documentary_transition(self):
        self.red();self.write_docs()
        path=self.root/'aikya/docs/specs/development/SPEC-001/tasks.md';path.parent.mkdir(parents=True)
        path.write_text('# Unapproved tasks\n\nGENERATED BY AIKYA FORGE\n')
        with self.assertRaises(ValueError):checks.refresh_preview(self.root,'iteration','author')

    def test_signed_transition_is_required_even_if_the_public_document_is_correct(self):
        self.red();self.write_docs()
        path=next((self.root/'.aikya/pi/documentation/operations').glob('*.json'))
        record=json.loads(path.read_text());record['mac']='0'*64;path.write_text(json.dumps(record))
        with self.assertRaises(ValueError):checks.refresh_preview(self.root,'iteration','author')

    def test_review_escalates_instead_of_omitting_a_large_document(self):
        self.red();self.data['documents'][0]['payload']['sections']['1-purpose-and-scope']='Details. '*800
        self.write_docs();(self.root/'value.txt').write_text('correct');self.snapshot();self.execute_check('green')
        with self.assertRaises(ValueError):context(self.root,'iteration')

    def test_pending_documentation_cannot_be_used_as_a_transition(self):
        self.red()
        with patch.object(docs,'_still_owned',side_effect=OSError('Interrupted after all writes')):
            with self.assertRaises(OSError):self.write_docs()
        with self.assertRaises(ValueError):checks.refresh_preview(self.root,'iteration','author')


if __name__=='__main__':unittest.main()
