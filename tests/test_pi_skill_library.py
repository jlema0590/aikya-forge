"""Global skill data never activates a project or imports executable client configuration."""
import importlib
import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch


class SkillLibraryTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(importlib.util.find_spec('aikya.services.skill_library'),'Owned inert skill library is absent')
        self.library=importlib.import_module('aikya.services.skill_library')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.base=Path(self.tmp.name).resolve()
        self.app=self.base/'application';self.source=self.base/'example-skill';self.source.mkdir()
        self.original=b'---\r\nname: example-skill\r\ndescription: Explain selected local conventions\r\nallowed-tools: Bash\r\n---\r\nUse the selected conventions.\r\n'
        (self.source/'SKILL.md').write_bytes(self.original)
        (self.source/'references').mkdir();(self.source/'references/guide.md').write_text('# Source guide\n\nPreserve these original bytes.\n')
        self.env=patch.dict('os.environ',{'AIKYA_INSTALL_ROOT':str(self.app)});self.env.start();self.addCleanup(self.env.stop)

    def install(self):
        value=self.library.preview(str(self.source))
        with self.assertRaises(ValueError):self.library.apply(value['plan'])
        return value,self.library.apply(value['plan'],approved=True)

    def test_combined_global_resource_path_is_refused_before_library_creation(self):
        (self.source/'references'/('x'*135+'.md')).write_text('A resource whose final cache path is too long.')
        with self.assertRaises(ValueError):self.library.preview(str(self.source))
        self.assertFalse(self.app.exists())

    def test_global_preview_and_empty_status_have_no_effects_or_project_activation(self):
        first=self.base/'one';second=self.base/'two';first.mkdir();second.mkdir()
        value=self.library.preview(str(self.source));status=self.library.status()
        self.assertEqual(value['review']['scope'],'global');self.assertEqual(value['review']['activation'],'none')
        self.assertIn('allowed-tools',value['review']['ignored_fields']);self.assertEqual(status['skills'],[])
        self.assertFalse(self.app.exists());self.assertEqual(list(first.iterdir()),[]);self.assertEqual(list(second.iterdir()),[])

    def test_confirmed_global_package_preserves_originals_and_remains_inert(self):
        value,result=self.install()
        self.assertEqual(result['status'],'installed');self.assertEqual(result['scope'],'global');self.assertEqual(result['activation'],'none')
        entries=self.library.status()['skills'];self.assertEqual(len(entries),1);self.assertEqual(entries[0]['name'],'example-skill')
        data=self.library.package('example-skill',result['source_hash'])
        self.assertEqual(data['raws']['SKILL.md'],self.original)
        self.assertTrue(data['prepared']['SKILL.md'].endswith(b'GENERATED BY AIKYA FORGE\n'))
        self.assertNotIn(b'\r\n',data['prepared']['SKILL.md'])
        self.assertFalse((self.app/'.claude').exists());self.assertFalse((self.app/'aikya/docs').exists())
        self.assertFalse(any(self.app.rglob('memory.db')))

    def test_source_changed_after_preview_never_installs_or_adopts_a_directory(self):
        plan=self.library.preview(str(self.source))['plan']
        (self.source/'SKILL.md').write_bytes(self.original+b'Changed after review.\n')
        with self.assertRaises(ValueError):self.library.apply(plan,approved=True)
        self.assertFalse(self.app.exists())

    def test_unowned_application_data_is_preserved(self):
        self.app.mkdir();custom=self.app/'custom.txt';custom.write_text('User data')
        with self.assertRaises(ValueError):self.library.preview(str(self.source))
        self.assertEqual(custom.read_text(),'User data');self.assertEqual(sorted(p.name for p in self.app.iterdir()),['custom.txt'])

    def test_an_existing_name_requires_an_explicit_update_and_is_not_overwritten(self):
        _,result=self.install();before=self.library.package('example-skill',result['source_hash'])['raws']
        (self.source/'SKILL.md').write_bytes(self.original+b'Another version.\n')
        with self.assertRaises(ValueError):self.library.preview(str(self.source))
        self.assertEqual(self.library.package('example-skill',result['source_hash'])['raws'],before)

    def test_modified_cached_bytes_are_preserved_and_cannot_be_selected(self):
        _,result=self.install();store=Path(result['package'])
        target=store/'files/SKILL.md';target.write_text('User-edited instructions')
        with self.assertRaises(ValueError):self.library.package('example-skill',result['source_hash'])
        self.assertEqual(target.read_text(),'User-edited instructions')

    def test_unlisted_cached_files_cannot_be_imported_as_a_global_package(self):
        _,result=self.install();store=Path(result['package']);extra=store/'files/unlisted.md';extra.write_text('Unapproved data')
        with self.assertRaises(ValueError):self.library.package('example-skill',result['source_hash'])
        self.assertEqual(extra.read_text(),'Unapproved data')

    def test_a_file_introduced_during_copy_is_preserved_and_no_package_is_adopted(self):
        from aikya.services import skill_packages
        preview=self.library.preview(str(self.source));actual=skill_packages.write_new;seen=[]
        def introduce(target,raw,**kwargs):
            if target.name=='SKILL.md' and not seen:
                seen.append(target);target.write_text('Concurrent user data')
            return actual(target,raw,**kwargs)
        with patch.object(skill_packages,'write_new',side_effect=introduce):
            with self.assertRaises(FileExistsError):self.library.apply(preview['plan'],approved=True)
        self.assertEqual(seen[0].read_text(),'Concurrent user data')
        self.assertEqual(self.library.status()['skills'],[])
        self.assertEqual(self.library.status()['status'],'pending')
        with self.assertRaises(ValueError):self.library.preview(str(self.source))

    def test_global_status_does_not_call_changed_cached_instructions_available(self):
        _,result=self.install();target=Path(result['package'])/'files/SKILL.md';target.write_text('Changed outside Aikya')
        status=self.library.status()
        self.assertEqual(status['status'],'degraded')
        self.assertEqual(status['skills'][0]['integrity'],'changed')
        self.assertEqual(target.read_text(),'Changed outside Aikya')

    def test_a_junction_application_root_is_not_adopted(self):
        with patch.object(Path,'is_junction',lambda path:path==self.app,create=True):
            with self.assertRaises(ValueError):self.library.preview(str(self.source))
        self.assertFalse(self.app.exists())


if __name__=='__main__':unittest.main()
