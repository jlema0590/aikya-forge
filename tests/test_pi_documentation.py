"""Native documentation records reviewed content, not technical approval."""
from pathlib import Path
import importlib,json,tempfile,unittest
from unittest.mock import patch
try:docs=importlib.import_module('aikya.services.documentation')
except ModuleNotFoundError:docs=None


class DocumentationTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(docs,'Native documentation service is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        (self.root/'.harness').mkdir();(self.root/'.harness/project-profile.json').write_text(json.dumps(dict(decisions=dict(backend='python',methodology='odd',mode='existing'))))
        (self.root/'main.py').write_text('VALUE = 1\n')
        self.item=dict(document='architecture',payload=dict(title='Observed architecture',sections={'1-purpose-and-scope':'A local Python module.'}))
        self.input=dict(action='write',documents=[self.item],sources=['main.py'])
        self.ident='REQ-20261108-abcde001'

    def preview(self,input_data=None,command='aikya-docs'):
        return docs.preview(self.root,command,input_data or self.input,'author-session')

    def apply(self,input_data=None,command='aikya-docs'):
        value=self.preview(input_data,command)
        with self.assertRaises(ValueError):docs.apply(self.root,value['plan'])
        return docs.apply(self.root,value['plan'],approved=True)

    def test_catalog_and_preview_are_read_only_and_show_concrete_content(self):
        catalog=docs.catalog(self.root,'architecture')
        self.assertIn('general-swe/foundations/architecture-overview',catalog['templates'])
        value=self.preview();review=value['review']['documents'][0]
        self.assertEqual(review['path'],'aikya/docs/architecture/architecture-overview.md')
        self.assertIn('A local Python module.',review['after']);self.assertIsNone(review['before'])
        self.assertFalse((self.root/'.aikya').exists());self.assertFalse((self.root/'aikya').exists())

    def test_confirmed_write_is_localized_stamped_indexed_and_records_no_execution(self):
        (self.root/'.aikya').mkdir();(self.root/'.aikya/docs-policy.json').write_text('{"schema_version":1,"language":"es"}')
        result=self.apply();self.assertEqual(result['status'],'documents_recorded');self.assertEqual(result['checks'],'not_run')
        target=self.root/'aikya/docs/architecture/architecture-overview.md';text=target.read_text()
        self.assertIn('Propósito y alcance',text);self.assertEqual(text.splitlines().count('GENERATED BY AIKYA HARNESS'),1)
        self.assertIn('architecture/architecture-overview.md',(self.root/'aikya/docs/indice.md').read_text())
        self.assertFalse(result['delivery_authorized']);self.assertFalse((self.root/'.claude').exists())

    def test_source_profile_language_and_plan_changes_invalidate_approval(self):
        plan=self.preview()['plan'];(self.root/'main.py').write_text('VALUE = 2\n')
        with self.assertRaises(ValueError):docs.apply(self.root,plan,approved=True)
        plan=self.preview()['plan'];path=self.root/'.harness/project-profile.json';path.write_text(path.read_text().replace('odd','sdd'))
        with self.assertRaises(ValueError):docs.apply(self.root,plan,approved=True)
        self.assertFalse((self.root/'aikya').exists())

    def test_custom_and_later_modified_documents_are_preserved(self):
        path=self.root/'aikya/docs/architecture/architecture-overview.md';path.parent.mkdir(parents=True);path.write_text('# Team-owned\n\nPreserve.\n')
        with self.assertRaises(ValueError):self.preview()
        self.assertEqual(path.read_text(),'# Team-owned\n\nPreserve.\n');path.unlink()
        self.apply();path.write_text(path.read_text().replace('A local Python module.','Owner customization.'))
        with self.assertRaises(ValueError):self.preview()
        self.assertIn('Owner customization.',path.read_text())

    def test_merge_preserves_unrelated_sections_and_noop_does_not_write(self):
        path=self.root/'aikya/docs/architecture/architecture-overview.md';path.parent.mkdir(parents=True)
        path.write_text('# Existing architecture\n\n## Team decisions\n\nKeep this decision.\n\nGENERATED BY AIKYA HARNESS\n')
        self.apply();self.assertIn('Keep this decision.',path.read_text())
        before={p.relative_to(self.root).as_posix():p.read_bytes() for p in self.root.rglob('*') if p.is_file()}
        value=self.preview();self.assertEqual(value['status'],'up_to_date');self.assertIsNone(value['plan'])
        self.assertEqual(before,{p.relative_to(self.root).as_posix():p.read_bytes() for p in self.root.rglob('*') if p.is_file()})

    def test_interrupted_write_is_preserved_without_automatic_replay(self):
        plan=self.preview()['plan'];original=docs.write_document
        def interrupted(root,*args,**kwargs):
            original(root,*args,**kwargs);raise OSError('Interrupted after first effect')
        with patch.object(docs,'write_document',side_effect=interrupted):
            with self.assertRaises(OSError):docs.apply(self.root,plan,approved=True)
        with self.assertRaises(ValueError):docs.apply(self.root,plan,approved=True)
        self.assertTrue((self.root/'aikya/docs/architecture/architecture-overview.md').exists())

    def test_empty_or_reserved_inputs_never_create_documentation(self):
        for data in (dict(action='write',documents=[],sources=['main.py']),
                     dict(action='write',documents=[dict(document='feature',payload={})],sources=['main.py']),
                     {**self.input,'sources':['.harness/project-profile.json']},
                     dict(action='write',documents=[{**self.item,'path':'specs/development/SPEC-001/tasks.md'}],sources=['main.py'])):
            with self.subTest(data=data),self.assertRaises(ValueError):self.preview(data)
        self.assertFalse((self.root/'aikya').exists())

    def baseline(self):
        return self.apply(dict(action='baseline',change_id=self.ident,sources=['main.py']),'aikya-docs-sync')

    def test_sync_without_material_changes_creates_no_request_or_documents(self):
        self.baseline()
        value=self.preview(dict(action='sync',change_id=self.ident,summary='Review only',documents=[self.item]),'aikya-docs-sync')
        self.assertEqual(value['status'],'no_changes');self.assertIsNone(value['plan'])
        self.assertFalse((self.root/'aikya/docs').exists())

    def test_sync_records_changed_sources_and_localized_request_without_certifying_checks(self):
        self.baseline();(self.root/'main.py').write_text('VALUE = 2\n')
        result=self.apply(dict(action='sync',change_id=self.ident,summary='Use the new value.',documents=[self.item]),'aikya-docs-sync')
        self.assertEqual(result['status'],'documents_recorded')
        path=self.root/('aikya/docs/changes/'+self.ident+'.md');body=path.read_text()
        self.assertIn('## Changes',body);self.assertIn('## Evidence',body);self.assertIn('## Updated documents',body)
        self.assertIn('main.py',body);self.assertIn('not run',body)
        with self.assertRaises(ValueError):self.preview(dict(action='sync',change_id=self.ident,summary='Again',documents=[self.item]),'aikya-docs-sync')

    def test_baseline_is_bound_to_its_author_and_detects_new_deleted_and_changed_files(self):
        self.apply(dict(action='baseline',change_id=self.ident,sources=['main.py','new.py']),'aikya-docs-sync')
        (self.root/'main.py').unlink();(self.root/'new.py').write_text('VALUE = 1\n')
        data=dict(action='sync',change_id=self.ident,summary='Replace the module.',documents=[self.item])
        with self.assertRaises(ValueError):docs.preview(self.root,'aikya-docs-sync',data,'different-author')
        value=self.preview(data,'aikya-docs-sync')
        self.assertEqual(set(value['review']['changes']),{'main.py','new.py'})

    def test_summary_cannot_link_private_evidence(self):
        private=self.root/'.aikya/pi/private.json';private.parent.mkdir(parents=True);private.write_text('{"private":true}')
        item=dict(document='summary',slug='observed-tests',payload=dict(title='Supplied results',sections={'what-was-tested':'Selected module','assessment':'Review supplied observations.'},evidence=['.aikya/pi/private.json']))
        with self.assertRaises(ValueError):self.preview({**self.input,'documents':[item]})
        self.assertFalse((self.root/'aikya/docs').exists())

    def test_registry_capacity_is_checked_before_document_effects(self):
        from aikya.review import authentication
        from aikya.core.checkpoints import identity
        authentication.key(self.root,create=True)
        path=self.root/'.aikya/pi/documentation/registry.json';path.parent.mkdir(parents=True)
        path.write_text(json.dumps(authentication.seal(self.root,dict(schema=1,project=identity(self.root),pages={'aikya/docs/design/'+str(n)+'.md':'0'*64 for n in range(200)}))))
        with self.assertRaises(ValueError):self.preview()
        self.assertFalse((self.root/'aikya/docs').exists())

    def test_embedded_duplicate_footer_is_refused_before_writing(self):
        item=dict(document='architecture',payload=dict(title='Architecture',sections={'1-purpose-and-scope':'A module.\nGENERATED BY AIKYA HARNESS\nMore text.'}))
        with self.assertRaises(ValueError):self.preview({**self.input,'documents':[item]})
        self.assertFalse((self.root/'aikya/docs').exists())

    def test_completed_request_cannot_replay_after_public_record_is_deleted(self):
        self.baseline();(self.root/'main.py').write_text('VALUE = 2\n')
        data=dict(action='sync',change_id=self.ident,summary='Changed value.',documents=[self.item])
        self.apply(data,'aikya-docs-sync');(self.root/('aikya/docs/changes/'+self.ident+'.md')).unlink()
        with self.assertRaises(ValueError):self.preview(data,'aikya-docs-sync')

    def test_external_change_during_effect_remains_pending_and_is_not_success(self):
        plan=self.preview()['plan'];original=docs.write_document
        def changed(root,*args,**kwargs):
            result=original(root,*args,**kwargs);(self.root/'main.py').write_text('UNREVIEWED = 9\n');return result
        with patch.object(docs,'write_document',side_effect=changed):
            with self.assertRaises(ValueError):docs.apply(self.root,plan,approved=True)
        with self.assertRaises(ValueError):self.preview()
        self.assertEqual((self.root/'main.py').read_text(),'UNREVIEWED = 9\n')

    def test_summary_binds_existing_report_and_does_not_approve_sdd(self):
        path=self.root/'report.tap';path.write_text('TAP version 13\n1..1\nok 1 - observed\n')
        item=dict(document='summary',slug='observed-tests',payload=dict(title='Supplied results',sections={'what-was-tested':'Selected module','assessment':'Review supplied observations.'},evidence=['report.tap']))
        data={**self.input,'documents':[item]};plan=self.preview(data)['plan'];path.write_text('Changed supplied report\n')
        with self.assertRaises(ValueError):docs.apply(self.root,plan,approved=True)
        profile=self.root/'.harness/project-profile.json';profile.write_text(profile.read_text().replace('odd','sdd'))
        result=self.apply(data);self.assertFalse(result['delivery_authorized']);self.assertFalse((self.root/'aikya/docs/specs').exists())

    def test_language_change_after_last_preview_cannot_write_unapproved_content(self):
        plan=self.preview()['plan'];original=docs._assemble;calls=0
        def changed(*args,**kwargs):
            nonlocal calls
            calls+=1
            if calls==3:
                path=self.root/'.aikya/docs-policy.json';path.parent.mkdir(exist_ok=True);path.write_text('{"schema_version":1,"language":"es"}')
            return original(*args,**kwargs)
        with patch.object(docs,'_assemble',side_effect=changed):
            with self.assertRaises(ValueError):docs.apply(self.root,plan,approved=True)
        self.assertFalse((self.root/'aikya/docs').exists())

    def test_sync_updated_documents_lists_actual_writes_only(self):
        self.apply();self.baseline();(self.root/'main.py').write_text('VALUE = 2\n')
        self.apply(dict(action='sync',change_id=self.ident,summary='Change the value.',documents=[self.item]),'aikya-docs-sync')
        text=(self.root/('aikya/docs/changes/'+self.ident+'.md')).read_text()
        self.assertNotIn('aikya/docs/architecture/architecture-overview.md',text)
        self.assertIn('aikya/docs/changes/'+self.ident+'.md',text)

    def test_document_payload_must_be_a_reviewable_object(self):
        for payload in ('instructions',[],None):
            item=dict(document='summary',slug='observed',payload=payload)
            with self.subTest(payload=payload),self.assertRaises(ValueError):self.preview({**self.input,'documents':[item]})
