"""Native SDD transitions reuse the canonical engine and explicit host approvals."""
import json
from pathlib import Path
import tempfile
import unittest


class NativeSddTests(unittest.TestCase):
    def setUp(self):
        from aikya.services import sdd as service
        self.service=service
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name).resolve();(self.root/'.harness').mkdir()
        (self.root/'.harness/project-profile.json').write_text(json.dumps({'decisions':{'project_type':'development','methodology':'sdd'}}))
        fixture=Path(__file__).resolve().parents[1]/'examples/sdd/development/order-api'
        self.raw={k:json.loads((fixture/(k+'.json')).read_text()) for k in ('spec','clarify','plan','tasks')}

    def transition(self,action,arguments):
        plan=self.service.preview(self.root,action,arguments)
        with self.assertRaises(ValueError):self.service.apply(self.root,plan)
        return self.service.apply(self.root,plan,approved=True)

    def test_full_stage_sequence_preserves_explicit_approvals_and_canonical_documents(self):
        self.transition('specify',{'input_data':self.raw['spec']})
        self.transition('clarify',{'ident':'SPEC-001','answers':self.raw['clarify']})
        for stage,action in [('spec','plan'),('plan','tasks'),('tasks',None)]:
            self.transition('approve',{'ident':'SPEC-001','stage':stage,'actor':'project-owner'})
            if action:self.transition(action,{'ident':'SPEC-001','raw':self.raw[action]})
        value=self.service.status(self.root,'SPEC-001')
        self.assertEqual(value['approved'],['plan','spec','tasks'])
        docs=self.root/'aikya/docs/specs/development/SPEC-001'
        self.assertTrue((docs/'tasks.md').read_text().endswith('GENERATED BY AIKYA HARNESS\n'))
        self.assertFalse((self.root/'.claude').exists())

    def test_changed_source_or_injected_operation_cannot_reuse_preview(self):
        plan=self.service.preview(self.root,'specify',{'input_data':self.raw['spec']})
        (self.root/'new.py').write_text('x=1')
        with self.assertRaises(ValueError):self.service.apply(self.root,plan,approved=True)
        with self.assertRaises(ValueError):self.service.preview(self.root,'shell',{'argv':['anything']})
        self.assertFalse((self.root/'aikya').exists())


if __name__=='__main__':unittest.main()
