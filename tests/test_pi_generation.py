"""Native generation is confirmed, source-bound and never replaces owner files."""
import importlib,json,tempfile,unittest
from pathlib import Path
from unittest.mock import patch
try:generation=importlib.import_module('aikya.services.generation')
except ModuleNotFoundError:generation=None


class GenerationTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(generation,'Native generation boundary is absent')
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name).resolve()
        (self.root/'.harness').mkdir();(self.root/'.harness/project-profile.json').write_text(json.dumps(dict(decisions=dict(backend='python',methodology='odd',mode='existing'))))
        (self.root/'source.py').write_text('VALUE = 1\n');self.files={'src/new.py':b'VALUE = 2\n'}

    def preview(self):return generation.preview(self.root,self.files,'author-session','bootstrap',dict(reason='Reviewed local artifact'))

    def test_preview_has_no_effects_and_shows_the_named_output(self):
        value=self.preview();self.assertEqual(value['review']['files'][0]['path'],'src/new.py')
        self.assertIn('VALUE = 2',value['review']['files'][0]['preview'])
        self.assertFalse((self.root/'.aikya').exists());self.assertFalse((self.root/'src').exists())

    def test_apply_requires_confirmation_and_records_actual_bytes_without_tests(self):
        value=self.preview();plan=value['plan']
        with self.assertRaises(ValueError):generation.apply(self.root,plan,self.files)
        result=generation.apply(self.root,plan,self.files,approved=True)
        self.assertEqual((self.root/'src/new.py').read_bytes(),b'VALUE = 2\n')
        self.assertEqual(result['status'],'generated');self.assertEqual(result['checks'],'not_run')
        self.assertFalse(result['delivery_authorized'])
        self.assertTrue((self.root/result['report']).read_text().endswith('GENERATED BY AIKYA FORGE\n'))
        self.assertIn(result['report'].removeprefix('aikya/docs/'),(self.root/'aikya/docs/indice.md').read_text())
        with self.assertRaises(ValueError):generation.apply(self.root,plan,self.files,approved=True)

    def test_existing_owner_files_are_preserved_and_not_counted_as_generated(self):
        (self.root/'src').mkdir();(self.root/'src/new.py').write_text('OWNER = True\n')
        value=self.preview();self.assertEqual(value['status'],'nothing_to_generate');self.assertIsNone(value['plan'])
        self.assertEqual(value['review']['preserved'],['src/new.py'])
        self.assertEqual((self.root/'src/new.py').read_text(),'OWNER = True\n')
        self.assertFalse((self.root/'aikya/docs').exists())

    def test_stale_source_profile_or_changed_payload_cannot_apply(self):
        plan=self.preview()['plan'];(self.root/'source.py').write_text('VALUE = 9\n')
        with self.assertRaises(ValueError):generation.apply(self.root,plan,self.files,approved=True)
        plan=self.preview()['plan']
        with self.assertRaises(ValueError):generation.apply(self.root,plan,{'src/new.py':b'UNREVIEWED = 1\n'},approved=True)
        self.assertFalse((self.root/'src').exists())

    def test_source_scope_requires_current_sdd_selection(self):
        path=self.root/'.harness/project-profile.json';path.write_text(path.read_text().replace('odd','sdd'))
        with self.assertRaises(ValueError):self.preview()
        self.assertFalse((self.root/'src').exists())

    def test_control_secrets_links_empty_and_oversized_outputs_are_refused(self):
        for files in ({},{'.env':b'secret'},{'.aikya/control.py':b'pass\n'},{'AGENTS.md':b'instructions'},{'../escape.py':b'pass'},{'huge.py':b'x'*1000001}):
            with self.subTest(files=list(files)),self.assertRaises(ValueError):generation.preview(self.root,files,'author-session','bootstrap',{})
        (self.root/'src').symlink_to(self.root/'.harness',target_is_directory=True)
        with self.assertRaises(ValueError):self.preview()

    def test_partial_effect_is_reserved_and_not_replayed(self):
        plan=self.preview()['plan'];original=generation.write_new
        def interrupted(path,*args,**kwargs):
            if str(path).endswith('/src/new.py'):raise OSError('Interrupted before copy')
            return original(path,*args,**kwargs)
        with patch.object(generation,'write_new',side_effect=interrupted):
            with self.assertRaises(OSError):generation.apply(self.root,plan,self.files,approved=True)
        with self.assertRaises(ValueError):generation.apply(self.root,plan,self.files,approved=True)
        self.assertFalse((self.root/'src/new.py').exists())

    def test_markdown_outputs_cannot_create_aikya_records_outside_docs(self):
        with self.assertRaises(ValueError):generation.preview(self.root,{'plans/change.md':b'# Plan\n\nDo work.\n'},'author-session','infra',{})

    def test_oversized_source_is_refused_before_any_generation_effect(self):
        self.files={'src/new.py':b'x\n'*1001}
        with self.assertRaises(ValueError):self.preview()
        self.assertFalse((self.root/'src').exists());self.assertFalse((self.root/'.aikya').exists())

    def test_concurrently_created_destination_is_never_overwritten(self):
        plan=self.preview()['plan'];original=generation.write_new
        def raced(path,raw):
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(b'OWNER RACE\n')
            return original(path,raw)
        with patch.object(generation,'write_new',side_effect=raced):
            with self.assertRaises(OSError):generation.apply(self.root,plan,self.files,approved=True)
        self.assertEqual((self.root/'src/new.py').read_bytes(),b'OWNER RACE\n')

    def test_changed_task_control_during_copy_preserves_uncertain_outcome(self):
        plan=self.preview()['plan'];original=generation.write_new
        def changed(path,raw):
            original(path,raw)
            control=self.root/'.aikya/pi/odd-workflow.json'
            control.parent.mkdir(parents=True,exist_ok=True);control.write_text('{}\n')
        with patch.object(generation,'write_new',side_effect=changed):
            with self.assertRaises(ValueError):generation.apply(self.root,plan,self.files,approved=True)
        self.assertTrue((self.root/'.aikya/pi/generation/pending.json').exists())
        self.assertFalse((self.root/'.aikya/pi/generation/operations').exists())
        self.assertEqual((self.root/'src/new.py').read_bytes(),self.files['src/new.py'])
