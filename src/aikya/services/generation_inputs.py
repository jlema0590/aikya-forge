"""Bounded immutable artifact descriptions and project generation provenance."""
import hashlib
from pathlib import Path
from aikya.code_index.policy import excluded,read_source
from aikya.core.checkpoints import safe_file
from aikya.documentation.layout import stamp,generated,canonical
from aikya.documentation.language import resolve
from aikya.review.contracts import encoded,identifier
from .documentation_inputs import profile
from .task_binding import candidate_revision

PENDING='.aikya/pi/generation/pending.json'


def sha(raw):return hashlib.sha256(raw).hexdigest()


def artifacts(root,files,session_id,category):
    identifier(session_id);identifier(category)
    if not isinstance(files,dict) or not 1<=len(files)<=100:raise ValueError('Select 1–100 generated files')
    rows=[];prepared={};preserved=[];total=0
    for name,raw in sorted(files.items()):
        if not isinstance(name,str) or not isinstance(raw,bytes) or len(raw)>1000000:raise ValueError('Bounded regular artifact required')
        if any(ord(c)<32 for c in name):raise ValueError('Control character in generation path')
        path=safe_file(root,name)
        if (excluded(name) or any(part.lower() in ('.agents','.codex','.pi') for part in name.split('/'))
                or path.name.upper() in ('AGENTS.MD','CLAUDE.MD','SKILL.MD')):raise ValueError('Protected generated destination')
        if path.suffix.lower()=='.md':
            if name.startswith('aikya/docs/'):
                if canonical(name)!=name.removeprefix('aikya/docs/') or name.lower().startswith(('aikya/docs/specs/','aikya/docs/features/','aikya/docs/tools/')) or name=='aikya/docs/indice.md':
                    raise ValueError('Use dedicated workflow for this document')
            elif category!='scaffold' or path.name not in ('README.md','README.es.md') or not (len(Path(name).parts)==1 or name.startswith(('apps/','packages/'))):
                raise ValueError('Aikya documentation belongs inside aikya/docs')
            raw=stamp(raw.decode('utf8')).encode()
            if raw.decode().splitlines().count('GENERATED BY AIKYA HARNESS')!=1:raise ValueError('Duplicate generated footer')
        elif name.startswith('aikya/docs/'):raise ValueError('Use dedicated state writer inside docs')
        from aikya.quality.source import validate_content
        validate_content(root,name,raw)
        total+=len(raw)
        if total>5000000:raise ValueError('Generated batch exceeds 5 MB')
        before=sha(read_source(root,name,1000000)) if path.exists() else None
        row=dict(path=name,sha256=sha(raw),bytes=len(raw),before=before,action='preserve' if before is not None else 'create')
        try:
            text=raw.decode('utf8');row['preview']=text[:1500];row['truncated']=len(text)>1500
        except UnicodeError:row.update(preview='Binary artifact; inspect its source and SHA-256',truncated=True)
        rows.append(row)
        if before is not None:preserved.append(name)
        else:prepared[name]=raw
    writable=[p for p in prepared if not p.startswith('aikya/docs/')]
    version=candidate_revision(root,writable,session_id) if writable else None
    if len(encoded(rows))>38000:raise ValueError('Split generated manifest into smaller reviewed batches')
    return dict(files=rows,preserved=preserved,prepared=prepared,workflow_revision=version)


def report(root,operation_id,category,rows,preserved,language):
    es=language=='es';title='Generación local' if es else 'Local generation'
    notice='Archivos locales registrados; pruebas, build y despliegue no ejecutados por la copia.' if es else 'Local files recorded; copying does not execute tests, builds or deployment.'
    return stamp('# '+title+' — '+operation_id+'\n\n'+notice+'\n\n```json\n'+encoded(dict(category=category,created=[dict(path=r['path'],sha256=r['sha256']) for r in rows if r['action']=='create'],preserved=preserved))+'\n```')
