"""Compose unique anchored text edits against original bytes without effects."""
from pathlib import Path
from aikya.code_index.policy import excluded,read_source
from aikya.core.checkpoints import safe_file
from aikya.quality.source import validate_content
from aikya.review.contracts import encoded
from aikya.review.document_transitions import digest_bytes


def destination(root,name):
    target=safe_file(root,name,write=True)
    if (excluded(name) or any(p.lower() in ('.codex','.agents','.pi') for p in name.split('/'))
            or target.name.upper() in ('AGENTS.MD','CLAUDE.MD','SKILL.MD')):
        raise ValueError('Protected batch destination')
    for parent in target.parents:
        if parent==root:break
        if parent.exists() and not parent.is_dir():raise ValueError('Destination parent is not a directory')
    return target


def patch_text(original,edits):
    if not isinstance(edits,list) or not 1<=len(edits)<=20:raise ValueError('Select bounded exact edits')
    ranges=[]
    for edit in edits:
        if (not isinstance(edit,dict) or set(edit)!={'old','new'} or not isinstance(edit['old'],str)
                or not edit['old'] or not isinstance(edit['new'],str)
                or max(len(edit['old']),len(edit['new']))>4000 or '\x00' in edit['old']+edit['new']):
            raise ValueError('Bounded nonempty original anchor required')
        start=original.find(edit['old'])
        if start<0 or original.find(edit['old'],start+1)>=0:raise ValueError('Anchor must match exactly once in original content')
        ranges.append((start,start+len(edit['old']),edit['new']))
    ranges.sort()
    if any(left[1]>right[0] for left,right in zip(ranges,ranges[1:])):raise ValueError('Overlapping edits are ambiguous')
    for start,end,value in reversed(ranges):original=original[:start]+value+original[end:]
    return original


def prepare(root,operations):
    if not isinstance(operations,list) or not 1<=len(operations)<=20:raise ValueError('Select 1–20 source operations')
    rows=[];prepared=[];seen=set();total=0
    for item in operations:
        if not isinstance(item,dict) or 'path' not in item:raise ValueError('Named source operation required')
        name=item['path'];target=destination(root,name)
        normalized=name.casefold()
        if any(normalized==p or normalized.startswith(p+'/') or p.startswith(normalized+'/') for p in seen):
            raise ValueError('Duplicate, case-aliased or conflicting parent destination')
        seen.add(normalized);raw=read_source(root,name,1000000) if target.exists() else None
        total+=len(raw) if raw is not None else 0
        if total>5000000:raise ValueError('Source batch exceeds 5 MB inspection bound')
        text=raw.decode('utf8') if raw is not None else None
        if text is not None and '\x00' in text:raise ValueError('Binary source is outside the text batch contract')
        row=dict(path=name,before=digest_bytes(raw) if raw is not None else None)
        if set(item)=={'path','content'}:
            after=item['content'];row.update(action='replace' if raw is not None else 'create',content=after)
        elif set(item)=={'path','edits'} and text is not None:
            after=patch_text(text,item['edits']);row.update(action='patch',edits=item['edits'])
        elif set(item)=={'path','delete'} and item['delete'] is True and text is not None:
            after=None;row.update(action='delete',content=text)
        else:raise ValueError('Choose content, existing-file edits or explicit existing-file deletion')
        if after is not None:
            if not isinstance(after,str) or '\x00' in after:raise ValueError('Regular UTF-8 text required')
            payload=after.encode('utf8')
            if len(payload)>1000000:raise ValueError('Patched file exceeds 1 MB')
            if target.suffix.lower()=='.md' and (not after.endswith('GENERATED BY AIKYA HARNESS\n')
                    or after.splitlines().count('GENERATED BY AIKYA HARNESS')!=1):raise ValueError('Unique final Markdown footer required')
            validate_content(root,name,payload)
        else:payload=None
        row.update(after=digest_bytes(payload) if payload is not None else None,bytes=len(payload) if payload is not None else 0)
        if row['before']==row['after']:raise ValueError('No-op source operations are unnecessary')
        rows.append(row);prepared.append(dict(**row,raw=payload,mode=target.stat().st_mode&0o777 if target.exists() else 0o644))
    if len(encoded(rows).encode())>48000:raise ValueError('Exact source review exceeds its bound; split the batch')
    return rows,prepared
