"""Ephemeral host grants for one source-bound write; not an OS sandbox."""
import hashlib
import time
from aikya.code_index.policy import project_root, excluded, read_source
from aikya.core.checkpoints import safe_file
from aikya.core.state import locked
from aikya.review.contracts import digest, encoded
from aikya.storage import atomic_write


def preview(root, intent, *, session=None):
    root = project_root(root)
    from .batch_records import guard
    guard(root)
    if not isinstance(intent, dict) or set(intent) != {'path', 'content'}:
        raise ValueError('Invalid write intent')
    path, content = intent['path'], intent['content']
    target = safe_file(root, path, write=True)
    if (excluded(path) or any(p.lower() in ('.codex', '.agents', '.pi') for p in path.split('/'))
            or target.name.upper() in ('AGENTS.MD', 'CLAUDE.MD', 'SKILL.MD') or not target.parent.is_dir()):
        raise ValueError('Protected write destination')
    if not isinstance(content, str) or '\x00' in content or len(content.encode('utf8')) > 12000:
        raise ValueError('Write exceeds the supported content bound')
    if target.suffix.lower() == '.md' and (not content.endswith('GENERATED BY AIKYA FORGE\n')
            or content.splitlines().count('GENERATED BY AIKYA FORGE')!=1):
        raise ValueError('Generated Markdown requires the Aikya footer')
    from aikya.quality.source import validate_content
    validate_content(root,path,content.encode('utf8'))
    before = hashlib.sha256(read_source(root, path, 1_048_576)).hexdigest() if target.exists() else None
    from .task_binding import revision
    workflow_revision=revision(root,path,session)
    return dict(workflow_revision=workflow_revision, path=path, before=before, after=hashlib.sha256(content.encode('utf8')).hexdigest(),
                intent_hash=digest(intent), bytes=len(content.encode('utf8')))


def issue(root, session, intent, key, *, now=None, ttl=120):
    """Trusted-host API only; grant creation is never a model operation."""
    from .authorization_tokens import issue as issue_token
    checked=preview(root,intent,session=session)
    return issue_token(root,session,checked,key,'file.write',now=now,ttl=ttl)


def _verify(root, session, intent, token, key, now):
    from .authorization_tokens import verify
    checked=preview(root,intent,session=session)
    return verify(root,session,checked,token,key,'file.write',now),checked


def apply_write(root, session, intent, token, key, *, now=None):
    root = project_root(root)
    data, checked = _verify(root, session, intent, token, key, time.time() if now is None else now)
    folder = safe_file(root, '.aikya/pi/authorizations/used.json').parent
    folder.mkdir(parents=True, exist_ok=True)
    with locked(folder):
        target = safe_file(root, intent['path'], write=True)
        data, checked = _verify(root, session, intent, token, key, time.time() if now is None else now)
        path = folder / (data['nonce'] + '.json')
        if path.exists(): raise ValueError('Grant consumed; reconcile without replay')
        # Reserve before the effect; a crash leaves an uncertain consumed attempt.
        atomic_write(path, encoded(dict(schema=1, status='pending', session=session,
                     intent_hash=checked['intent_hash'], source_revision=checked['before'])) + '\n', mode=0o600)
        mode = target.stat().st_mode & 0o777 if target.exists() else 0o644
        atomic_write(target, intent['content'], mode=mode)
        if hashlib.sha256(read_source(root, intent['path'], 12000)).hexdigest() != checked['after']:
            raise ValueError('Write readback failed; reconcile attempt')
        result = dict(path=intent['path'], before=checked['before'], after=checked['after'], status='written')
        from .maintenance import after_write
        result['memory']=after_write(root)
        atomic_write(path, encoded(dict(schema=1, session=session, **result)) + '\n', mode=0o600)
        return result
