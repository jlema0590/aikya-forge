"""Prepare current-source external trial instructions; never execute or accept trials."""
import argparse
import importlib.util
import json
from pathlib import Path
from aikya.installation.bootstrap import state
from aikya.installation.managed_runtime import _read
from aikya.installation.managed_versions import parts
from aikya.storage import write_new


def prepare(source,output):
    source=state.safe(Path(source).absolute()).resolve(strict=True)
    output=state.safe(Path(output).absolute()).resolve(strict=False)
    if output.exists() or output.is_relative_to(source):
        raise ValueError('Select a new external packet directory outside the source checkout')
    spec=importlib.util.spec_from_file_location('_forge_packet_gate',Path(__file__).with_name('forge_release_gate.py'))
    gate=importlib.util.module_from_spec(spec);spec.loader.exec_module(gate)
    version=_read(state.safe(source/'VERSION'),128).decode('ascii').strip();parts(version)
    procedure=_read(state.safe(source/'aikya/docs/validation/forge-provider-procedure.md'),1000000)
    fingerprint=gate.runtime_fingerprint(source)
    review=dict(schema=1,version=version,runtime_fingerprint=fingerprint,review_status='pending',
                repetitions=0,observations=[],cache_conditions='',review_note='',checks={name:'not_run' for name in gate.CHECKS})
    result=dict(schema=1,status='prepared_not_executed',version=version,runtime_fingerprint=fingerprint,
                minimum_independent_trials=3,provider_calls=0,publication_authorized=False,checks=list(gate.CHECKS))
    if gate.runtime_fingerprint(source)!=fingerprint:raise ValueError('Source changed while preparing the external packet')
    body=('# Forge '+version+' external acceptance packet\n\n'
          +'Status: prepared, not executed or accepted. No provider calls or credentials were used.\n\n'
          +'Expected runtime fingerprint: `'+fingerprint+'`. Build/install that exact source before trials. '
          +'A source change invalidates this packet and all previous observations.\n\n'
          +'Use forge-provider-procedure.md for the nine scenarios. Keep model, effort, task, '
          +'tools and cache conditions explicit. Run at least three independent controlled trials '
          +'under finite approved token/call/time limits in the agreed external environment.\n\n'
          +'For each counted trial, create a separate pristine copy of the same fixture project '
          +'with a new project-local ledger/session. Export exactly once per copy. Multiple '
          +'filenames from one project aggregate its cumulative ledger and are not independent trials.\n\n'
          +'Export each fresh observation with the installed CLI: '
          +'`aikya acceptance export --target /absolute/project --output aikya/docs/validation/observation-01.json`. '
          +'Use different names; never overwrite evidence or edit exports to invent missing usage.\n\n'
          +'Only after human provenance review, copy the observations and completed review into '
          +'the release source validation dossier and run: '
          +'`python scripts/ci/forge_release_gate.py --version '+version+' --report '
          +'aikya/docs/validation/forge-provider-acceptance.json`. The included pending review '
          +'cannot pass publication. This packet does not authorize merging or delivery.\n\n'
          +'Record visual terminal, keyboard, theme and resize acceptance separately on each OS.\n\n'
          +'GENERATED BY AIKYA HARNESS\n')
    output.mkdir(parents=True)
    for name,data in [('metadata.json',json.dumps(result,indent=2)+'\n'),('forge-provider-acceptance.json',json.dumps(review,indent=2)+'\n'),
                      ('forge-provider-procedure.md',procedure),('README.md',body)]:
        write_new(state.safe(output/name),data,mode=0o600)
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=Path(__file__).resolve().parents[2])
    parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
    print(json.dumps(prepare(args.source,args.output),sort_keys=True))


if __name__=='__main__':main()
