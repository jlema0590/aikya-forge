"""Synthetic installed-package acceptance data; never reads personal project sources."""
import json
from pathlib import Path
import sys
from aikya.installation import portable
from aikya.code_index.policy import CODE_SUFFIXES
from aikya.code_index.parsers.registry import parse_file
from aikya.memory.knowledge import remember,propose
from aikya.services import maintenance,memory,selected_skills
from aikya.cli.commands import BOOTSTRAP_COMMANDS

root=Path(sys.argv[1]).resolve();root.mkdir(parents=True,exist_ok=True)
source=root/'source.py';source.write_bytes(b'class StableEvidence: pass\n')
profile=dict(project_type='development',mode='existing',methodology='odd',repository_layout='singlerepo',backend='python')
portable.apply(root,portable.preview(root,profile,language='en'),approved=True)
samples={'.py':'class MemoryEvidence: pass\n','.pyi':'class MemoryEvidence: ...\n',
    '.java':'class MemoryEvidence { int value() { return 1; } }',
    '.cs':'public class MemoryEvidence { public int Value() => 1; }',
    '.go':'package example\ntype MemoryEvidence struct {}\nfunc Value() int { return 1 }\n',
    '.dart':'class MemoryEvidence { int value() => 1; }'}
for suffix in ('.js','.jsx','.mjs','.cjs'):samples[suffix]='class MemoryEvidence { value() { return 1; } }'
for suffix in ('.ts','.tsx'):samples[suffix]='class MemoryEvidence { value(): number { return 1; } }'
folder=root/'src';folder.mkdir();coverage={}
for suffix in sorted(CODE_SUFFIXES):
    value=samples.get(suffix,'// Synthetic inventory-only evidence\n');name='memory'+suffix
    (folder/name).write_bytes(value.encode());parsed=parse_file(name,value.encode())
    coverage[suffix]=dict(status=parsed.status,parser=parsed.parser_id,symbols=len(parsed.symbols))
note=dict(kind='project',source='source.py',text='Acceptance decision: project-local memory survives runtime changes',ttl_days=30)
remember(root,note,approved=True);propose(root,{**note,'text':'UNREVIEWED_ACCEPTANCE_NOTE'})
result=maintenance.after_write(root);assert result['status']=='updated',result
assert len(memory.search(root,'Acceptance decision',2000)['notes'])==1
assert 'UNREVIEWED_ACCEPTANCE_NOTE' not in json.dumps(memory.search(root,'Acceptance',2000))
# An inert selected package is independent of the runtime distribution.
package=root.parent/'acceptance-skill';package.mkdir()
(package/'SKILL.md').write_bytes(b'---\nname: acceptance-skill\ndescription: Synthetic accepted conventions\n---\nUse only the selected conventions.\n')
selected_skills.apply(root,selected_skills.preview(root,str(package))['plan'],approved=True)
# Run the complete portable onboarding dimension in installed code.
cases=[]
for kind in ('development','infrastructure','devops'):
    for method in ('odd','sdd'):
        for mode in ('new','existing'):
            for language in ('en','es'):
                target=root.parent/'profiles'/('-'.join((kind,method,mode,language)));target.mkdir(parents=True)
                arguments=dict(project_type=kind,mode=mode,methodology=method,repository_layout='singlerepo')
                if kind=='development':arguments['backend']='python'
                elif kind=='infrastructure':arguments['infrastructure']={'iac':'terraform'}
                else:arguments['deployment']='docker'
                if mode=='existing':(target/'existing.py').write_bytes(b'class ExistingEvidence: pass\n')
                value=portable.apply(target,portable.preview(target,arguments,language=language),approved=True)
                assert value['status']=='initialized';assert not (target/'.claude').exists()
                assert all(not (target/name).exists() for name in ('docs','plans','bugs','features'))
                assert all(p.read_text().endswith('GENERATED BY AIKYA HARNESS\n') for p in (target/'aikya/docs').rglob('*.md'))
                cases.append(dict(type=kind,methodology=method,mode=mode,language=language,status='initialized'))
print(json.dumps(dict(coverage=coverage,profiles=cases,commands=list(BOOTSTRAP_COMMANDS),memory=result)))
